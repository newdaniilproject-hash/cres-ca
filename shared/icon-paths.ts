// ── Геометрия значков. ОБЩИЙ СЛОЙ ───────────────────────────────────────────
//
// Значок в реестре модулей (`public.modules.icon`) — это ИМЯ, а не картинка.
// Сама геометрия лежит здесь и читается обоими приложениями: веб рисует её
// инлайновым SVG (`components/icons.tsx`), телефон — через `react-native-svg`.
//
// ЗАЧЕМ ОДИН ИСТОЧНИК. Значок раздела — это то, по чему человек находит
// вкладку, не читая подпись. Разъехавшись, они дают продукт, где склад
// на сайте помечен коробкой, а в приложении чем-то другим: человек ищет
// глазами знакомую форму и не находит. Разъезжаются такие пары молча
// и обнаруживаются не разработчиком, а пользователем.
//
// ПОЧЕМУ ПРИМИТИВЫ, А НЕ ГОТОВАЯ РАЗМЕТКА. Строка `<svg>…</svg>` из веба
// в React Native не работает вовсе: там свои компоненты `Path`, `Circle`,
// `Rect`. Поэтому здесь лежат ЧИСЛА, а разметку каждый строит сам —
// ровно та же граница, что у остального общего слоя: общее — данные,
// своё — рисование.
//
// ЕДИНЫЕ ДЛЯ ВСЕХ ЗНАЧКОВ: сетка 24×24, линия 1.75, скруглённые концы,
// заливки нет, цвет наследуется от подписи. Эти величины НЕ повторяются
// у каждого значка — они свойство набора, и лежат в отрисовщике.

