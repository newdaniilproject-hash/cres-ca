// Адрес проекта Supabase. Повторён здесь, а не импортирован из
// `lib/supabase/config.ts`: конфиг собирается до применения путевых
// псевдонимов tsconfig, и `@/lib/...` отсюда не разрешается.
// Значение публичное (см. шапку того файла), расхождение ловится тем,
// что оба места читают одну и ту же переменную окружения.
const SUPABASE_ORIGIN = new URL(
  process.env.NEXT_PUBLIC_SUPABASE_URL ?? 'https://jobvstdwoyifspaiwazn.supabase.co',
).origin

// ── Заголовки безопасности. Шаг 6, пункт второй ────────────────────────────
//
// Политика собрана НЕ по шаблону, а по тому, что живой сайт действительно
// грузит. Инвентаризация 17.08.2026 на https://cres-ca.com — главная,
// карта, вход:
//
//   скрипты   • /_next/… (свои сборки)
//             • https://static.cloudflareinsights.com/beacon.min.js —
//               аналитика Cloudflare. Её вставляет САМ Cloudflare в наш
//               ответ, в репозитории её нет; забыть про неё значит молча
//               выключить аналитику владельца.
//             • https://cdn.jsdelivr.net/npm/qrcode — лист наклеек на
//               ёмкости (`lib/report/labels.ts`). Печать наклеек — это
//               требование Техрегламенту, а не украшение.
//   стили     • /_next/… плюс встроенные <style> Next и Tailwind
//   шрифты    • свои: next/font/google скачивает Inter на сборке
//   картинки  • свои, data:, blob:, Supabase Storage (фото товаров),
//               https://tile.openstreetmap.org (плитки Leaflet)
//   запросы   • свои, Supabase (вход, чтения витрины, хранилище),
//               /cdn-cgi/rum — маяк Cloudflare, свой домен
//   кадры     • ни одного
//
// ── Инлайновые скрипты: почему НЕ nonce и почему НЕ хеш ────────────────────
//
// Своих инлайновых скриптов три, все статические: тема (`components/theme`),
// признак обёртки (`components/native-boot`), язык (`lib/i18n/cookie`).
// Их хеши считаются тривиально. Но на живой странице инлайновых скриптов
// ПЯТЬ: два оставшихся — это `self.__next_f.push([...])`, то есть поток
// RSC самого Next. Их содержимое разное на каждой странице и меняется
// с каждой сборкой, хеш к ним не приделать.
//
// Отсюда развилка, и обе ветки проверены:
//
//   ХЕШИ не подходят. Как только в `script-src` появляется хоть один хеш,
//   браузер по спецификации ИГНОРИРУЕТ `'unsafe-inline'` — и блокирует
//   поток RSC, то есть весь интерфейс. Посчитать хеши наших трёх и на этом
//   успокоиться нельзя: политика стала бы строже ровно настолько, чтобы
//   сломать продукт, и ни на сколько безопаснее.
//
//   NONCE не подходит. Next умеет раздавать nonce своим скриптам, но nonce
//   обязан быть новым на каждый ответ — а значит страница перестаёт быть
//   кешируемой. Витрину индексируют, у `/` стоит revalidate 120, у `/t/<slug>`
//   — 60; менять их на «динамически всегда» ради CSP нельзя (правило 6).
//
// Поэтому `script-src 'self' 'unsafe-inline'` — и это названо честно:
// от инъекции инлайнового скрипта такая политика НЕ защищает. Она защищает
// от остального, и это не мало: подгрузить скрипт с чужого домена нельзя,
// увести данные запросом на чужой домен нельзя, подменить <base> нельзя,
// встроить сайт в кадр нельзя, отправить форму на чужой адрес нельзя.
//
// Дорога к строгой политике открыта и лежит через витрину: когда она
// переедет на языковой сегмент адреса и перестанет читать куку в корневом
// макете, кабинет (он и так динамический) можно будет закрыть отдельной
// nonce-политикой, оставив витрине эту.
//
// ── Обёртка Capacitor (шаг 8) ──────────────────────────────────────────────
//
// Приложение открывает БОЕВОЙ САЙТ в веб-вью (`server.url` в
// capacitor.config.ts), то есть эти заголовки действуют и внутри него —
// сломанная CSP ломает и приложение, а увидят это только на телефоне.
// Поэтому `capacitor:` и `ionic:` стоят в источниках картинок, запросов
// и медиа: через них веб-вью отдаёт локальные файлы (снимок камеры,
// кэш плагина), и на Android при `androidScheme: 'https'` — они же.
// В обычном браузере эти схемы не значат ничего и ничему не мешают.
// Переход на `cresca://` (возврат из внешнего браузера после Apple/Google)
// CSP не касается вовсе: это навигация верхнего уровня.
//
// ── Чего здесь НЕТ намеренно ───────────────────────────────────────────────
//
// Strict-Transport-Security сайт уже отдаёт (`max-age=63072000`), и стоит
// перед ним Cloudflare — второй такой же заголовок ничего не добавит,
// а `includeSubDomains` — это решение владельца, потому что поддомены
// продавцов ещё не заведены.

const CSP = [
  "default-src 'self'",
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'none'",
  "form-action 'self'",
  "frame-src 'self'",
  "manifest-src 'self'",
  "worker-src 'self' blob:",
  "script-src 'self' 'unsafe-inline' https://static.cloudflareinsights.com https://cdn.jsdelivr.net",
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self' data:",
  `img-src 'self' data: blob: ${SUPABASE_ORIGIN} https://tile.openstreetmap.org capacitor: ionic:`,
  "media-src 'self' blob: capacitor: ionic:",
  [
    "connect-src 'self'",
    SUPABASE_ORIGIN,
    SUPABASE_ORIGIN.replace('https://', 'wss://'),
    'https://cloudflareinsights.com',
    'capacitor:',
    'ionic:',
  ].join(' '),
].join('; ')

const SECURITY_HEADERS = [
  { key: 'Content-Security-Policy', value: CSP },
  // Дублирует frame-ancestors для браузеров, которые её не понимают.
  { key: 'X-Frame-Options', value: 'DENY' },
  // Без него браузер «додумывает» тип по содержимому: загруженный
  // документ, объявленный как image/png, мог бы поехать как HTML.
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  // Наружу уходит только домен, никогда путь. Это не про приватность
  // вообще, а про конкретную утечку: адрес приглашения — это
  // `/invite/<секрет>`, и полный Referer подарил бы его чужому сайту.
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  // Камера нужна сканеру штрихкодов, остальное продукту не нужно.
  // Геолокация оставлена себе: карта — очевидное место, где она появится,
  // а запрет здесь выглядел бы как поломка карты, а не как решение.
  {
    key: 'Permissions-Policy',
    value: 'camera=(self), geolocation=(self), microphone=(), payment=(), usb=(), browsing-topics=()',
  },
]

const config: NextConfig = {
  // Витрина каждого продавца живёт на своём поддомене, поэтому
  // изображения приходят с домена Storage нашего проекта Supabase.
  images: {
    remotePatterns: [
      { protocol: 'https', hostname: '*.supabase.co', pathname: '/storage/v1/object/public/**' },
    ],
  },

  // ── Возврат на уже открытую вкладку — из памяти, а не с сервера ──────
  //
  // Отзыв владельца 18.08.2026: «переход между табами прогружается где-то
  // секунду, а должен быть мгновенным». Секунда честная: страницы кабинета
  // `force-dynamic`, каждая ходит в базу в Ирландию, и ПЕРВОЕ открытие
  // быстрее физики не станет.
  //
  // Но нижняя панель существует ровно для того, между чем прыгают
  // десятки раз за смену (CLAUDE.md, решение 15.08.2026): склад → записи →
  // склад. И вот этот ВОЗВРАТ сервера не требует — ответ уже был в руках
  // минуту назад. По умолчанию Next держит `dynamic: 0`, то есть выбрасывает
  // динамический ответ сразу, и каждый прыжок туда-обратно платит полный
  // круг заново.
  //
  // 30 секунд — окно самого прыжка, а не «кеш данных». Чем платим, названо
  // прямо: если данные поменял ДРУГОЙ человек с другого устройства, на
  // возврате видно состояние до получаса-минуты назад. Свои изменения этим
  // не задеты — каждое действие кабинета зовёт `router.refresh()`, а он
  // окно сбрасывает.
  //
  // Чего этот параметр НЕ делает: он не кеширует ничего на сервере и не
  // трогает RLS. Это память маршрутизатора в одной вкладке одного человека.
  experimental: {
    staleTimes: { dynamic: 30 },
  },

  // Заголовки задаются здесь, а не в `proxy.ts`, по двум причинам.
  // Первая: они попадают и на статику `/_next/static/*`, которую middleware
  // не видит (её отсекает matcher). Вторая и главная: `headers()` — это
  // правило маршрутизации, оно не заставляет страницу отрисовываться
  // на каждый запрос. Тот же заголовок, выставленный в middleware вместе
  // с nonce, сделал бы витрину динамической — а её кешируемость и есть
  // ограничение, из которого выбран весь остальной вид политики.
  async headers() {
    return [{ source: '/:path*', headers: SECURITY_HEADERS }]
  },
}

export default config
