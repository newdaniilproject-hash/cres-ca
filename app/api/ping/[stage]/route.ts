// Заведён 12.08.2026, чтобы увидеть, до какой точки доходит запуск
// страницы внутри нативной обёртки. Симптом: «This page couldn't load»
// при том, что сама страница ДОЕЗЖАЕТ и разбирается — в логах Vercel
// видно GET /m 200, следом GET /manifest.webmanifest 304, а манифест
// запрашивается только после разбора HTML. Значит ломается то, что
// происходит после разбора и до первой отрисовки.
//
// Единственный способ вытащить текст оттуда — сетевой запрос: консоль
// веб-вью на устройстве недоступна. Ступень кодируется ПУТЁМ, а не
// query-параметром: в логах Vercel группировка идёт по requestPath,
// и /api/ping/boot видно сразу, а ?stage=boot — нет.
//
// Отвечает 204 без тела: маячку нечего возвращать, а пустой ответ
// дешевле всего. Ни базы, ни авторизации здесь нет и быть не должно.
//
// Service worker этот путь не перехватывает — в public/sw.js стоит
// ранний выход на /api/ (строка с url.pathname.startsWith('/api/')),
// поэтому специально ничего делать не надо.

// Ответ из кеша бесполезен: нужен факт вызова, а не тело.
export const dynamic = 'force-dynamic'

export async function GET(
  req: Request,
  { params }: { params: Promise<{ stage: string }> },
) {
  const { stage } = await params
  // Единственный вывод: он и есть показание прибора. Попадает в логи
  // Vercel, откуда читается глазами.
  console.log('[PING]', stage, Object.fromEntries(new URL(req.url).searchParams))

  return new Response(null, {
    status: 204,
    headers: { 'Cache-Control': 'no-store, max-age=0' },
  })
}
