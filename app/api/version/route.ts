import { NextResponse } from 'next/server'

// Какая сборка сейчас РАЗВЁРНУТА. Одна строка, и она нужна затем, чтобы
// приложение подхватывало новую версию само.
//
// ── ЗАЧЕМ ЭТО ВООБЩЕ ───────────────────────────────────────────────────────
//
// Отзыв владельца 25.08.2026: «сделай так, чтобы любое изменение было
// мгновенное и не требовало дополнительно обновлять страницу или
// перезаходить в приложение».
//
// Половину этого продукт уже умел: `components/app-shell.tsx` тихо
// перезапрашивает СОДЕРЖИМОЕ при возврате в приложение. Но содержимое —
// это данные, а не КОД: бандл остаётся тот, что приехал при открытии.
// Выкатили новую версию — человек её не видит, пока не закроет приложение
// начисто. Ровно это и произошло сегодня («визуально приложение вообще
// не изменилось»).
//
// ── ПОЧЕМУ НЕ ЧЕРЕЗ SERVICE WORKER ─────────────────────────────────────────
//
// В `components/pwa.tsx` уже висел обработчик `updatefound`, который
// показывает предложение обновиться. Он не срабатывал НИ РАЗУ и сработать
// не мог: `public/sw.js` — статический файл с `const VERSION = 'v3'`,
// байт в байт одинаковый во всех сборках. Браузер сравнивает САМ ФАЙЛ
// воркера; не изменился файл — нет и события. Механизм был, а работать
// не мог по построению.
//
// Чинить это «поднимать VERSION при каждом выкате» нельзя — ручное
// действие, привязанное к чужому событию, уже описано в шапке `sw.js`
// как оплаченная ошибка (пункт «VERSION не менялся никогда»).
//
// Поэтому спрашиваем не воркера, а сервер: что за сборка отвечает
// ПРЯМО СЕЙЧАС. Ответ сравнивается с тем, что вшито в работающий бандл
// (`NEXT_PUBLIC_BUILD_ID`, подставляет `next.config.ts` на сборке).
//
// ── ЧТО ОТДАЁМ ─────────────────────────────────────────────────────────────
//
// `VERCEL_GIT_COMMIT_SHA` — хеш коммита, из которого собрано развёрнутое.
// Вне Vercel (локальная разработка) обе стороны получают `dev`, значит
// не совпасть не могут, и никакого перезапуска в разработке не случится.
//
// Ничего чувствительного здесь нет: тот же хеш публично виден в GitHub.
export const dynamic = 'force-dynamic'

export function GET() {
  return NextResponse.json(
    { id: process.env.VERCEL_GIT_COMMIT_SHA ?? 'dev' },
    // Без этого ответ осел бы в кеше CDN и вечно сообщал бы о старой
    // сборке — то есть проверка свежести сама стала бы несвежей.
    { headers: { 'Cache-Control': 'no-store, max-age=0' } },
  )
}
