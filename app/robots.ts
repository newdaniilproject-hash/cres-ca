import type { MetadataRoute } from 'next'
import { SITE_URL, abs } from '@/lib/site'

// robots.txt. До 15.08.2026 его не было вовсе — адрес отдавал 404,
// и это не мелочь: продукт продаёт витрину, которую должны находить.
//
// Что закрыто и почему. Кабинет, аккаунт покупателя и весь вход — не потому,
// что там секреты (их защищает RLS, а не этот файл), а потому что боту там
// нечего индексировать: он увидит форму входа и запишет её как содержимое
// сорока адресов сразу. То же с `/m` — это воронка приложения, дубль входа.
//
// `/api` закрыт отдельной строкой: ручки отвечают JSON, и попадание такого
// ответа в выдачу — чистый мусор в индексе.
//
// Открыто ровно то, что имеет смысл в поиске: главная, поиск, карта
// и витрины магазинов `/t/<slug>`.
export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: '*',
        allow: '/',
        disallow: [
          '/api/',
          '/app/',
          '/account',
          '/auth/',
          '/login',
          '/register',
          '/forgot',
          '/m',
          // Служебная страница офлайна: её показывает service worker,
          // в выдаче она означала бы «сайт не работает».
          '/offline',
        ],
      },
    ],
    sitemap: abs('/sitemap.xml'),
    host: SITE_URL,
  }
}
