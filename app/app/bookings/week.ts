import { formatInputDay } from '@/lib/i18n/format'

// Календарная арифметика недельной сетки.
//
// ГЛАВНОЕ РЕШЕНИЕ ФАЙЛА: неделя — это СТРОКА `ГГГГ-ММ-ДД`, а не `Date`.
// Она живёт в адресе (`?week=2026-08-17`), её читает сервер в UTC,
// а рисует браузер в поясе заведения. Складывать сутки к `Date`
// в такой паре нельзя: у местной полуночи смещение, и на переводе
// часов или на границе месяца сложение промахивается на день.
// Со строкой промахнуться негде — арифметика идёт в `Date.UTC`,
// где смещения не существует вовсе.
//
// Единственное место, где появляется часовой пояс, — `dayOf()`: он
// отвечает на вопрос «в какой календарный день ЧЕЛОВЕК видит этот
// момент». Ответ зависит от того, кто спрашивает, и это правильно:
// в браузере мастера получится его местный день, ровно как и в списке
// дня, который печатает время без указания пояса.

const RE_DAY = /^\d{4}-\d{2}-\d{2}$/

/** Строка дня из момента времени — по МЕСТНЫМ частям, как в `<input type="date">`. */
export const dayOf = (v: Date | string | number = new Date()): string => formatInputDay(v)

/** Значение из адреса — настоящий календарный день, а не мусор. */
export function isDay(v: unknown): v is string {
  if (typeof v !== 'string' || !RE_DAY.test(v)) return false
  const d = new Date(`${v}T00:00:00Z`)
  // Проверка «дата не переехала» ловит 2026-02-31: `Date` его примет
  // и молча превратит в 3 марта, а адрес показывал бы одну неделю,
  // сетка — другую.
  return !Number.isNaN(d.getTime()) && d.toISOString().slice(0, 10) === v
}

/** Сдвиг на сутки. Только UTC-полночь — см. шапку файла. */
export function shiftDay(day: string, days: number): string {
  const d = new Date(`${day}T00:00:00Z`)
  d.setUTCDate(d.getUTCDate() + days)
  return d.toISOString().slice(0, 10)
}

/**
 * Понедельник недели, в которую попал день.
 *
 * Неделя начинается с понедельника, а не с воскресенья: так её ведут
 * в Украине, и так же подписаны рабочие дни мастера (`staff.weekday.*`,
 * где 1 — понеділок). Брать первый день из `Intl` нельзя — он зависит
 * от языка интерфейса, и у английской локали неделя начиналась бы
 * с воскресенья, то есть сетка ехала бы от переключателя языка.
 */
export function mondayOf(day: string): string {
  const dow = new Date(`${day}T00:00:00Z`).getUTCDay() // 0 — воскресенье
  return shiftDay(day, dow === 0 ? -6 : 1 - dow)
}

/** Семь дней недели от понедельника. */
export const weekDays = (monday: string): string[] =>
  Array.from({ length: 7 }, (_, i) => shiftDay(monday, i))

/** Адрес недельного вида. Сборщик один: ссылки на неделю теперь строят
 *  и сетка, и веб-хедер экрана, а разъехавшийся параметр в адресе —
 *  это две «одинаковые» стрелки, ведущие в разные недели. */
export const weekHref = (monday: string): string =>
  `/app/bookings?view=week&week=${monday}`

/**
 * Подпись недели. `formatRange` сам решает, что вынести за скобки:
 * «17–23 серпня 2026 р.» в одном месяце и «29 червня – 5 липня 2026 р.»
 * на стыке. Собирать это подстановкой руками — значит написать правило
 * склейки для каждого языка заново.
 *
 * `T00:00:00` без зоны читается как местная полночь, поэтому и на
 * сервере, и в браузере это ровно тот же календарный день — подпись
 * совпадает, гидратация не спорит.
 */
export function weekLabel(locale: string, monday: string): string {
  const at = (day: string) => new Date(`${day}T00:00:00`)
  return new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'long', year: 'numeric' })
    .formatRange(at(monday), at(shiftDay(monday, 6)))
}
