import { redirect } from 'next/navigation'
import { currentMembership, can, hasModule } from '@/lib/tenant'

export const dynamic = 'force-dynamic'

// ── Вход в кабинет: КУДА открывается приложение ─────────────────────────────
//
// Решение владельца 30.08.2026: кабинет открывается СКЛАДОМ, а не сводкой
// «Сьогодні». Причина продуктовая, а не вкусовая — продукт продаётся как
// «склад для майстрів», и первое, что человек делает утром, он делает
// на складе. Сводка никуда не делась: она живёт своим адресом
// `/app/today` и стоит первым пунктом меню разделов.
//
// ⚠️ ПОЧЕМУ ЭТО НЕ ПРОСТО `redirect('/app/inventory')` И НИКОГДА ИМ
// НЕ СТАНЕТ. `/app` — адрес, куда уходит `redirect('/app')` со всех
// экранов кабинета при отказе по праву (два десятка страниц). Безусловный
// редирект отсюда на склад даёт человеку без `stock.read` вечный круг
// `/app` → `/app/inventory` → `/app` и пятисотую ошибку вместо кабинета.
//
// Поэтому здесь спрашиваются ОБЕ оси доступа — ровно те же, что стоят
// на самой странице склада (`app/app/inventory/page.tsx`): право человека
// `stock.read` и модуль заведения `inventory`. Не совпади они с проверками
// склада — круг вернётся; это единственное место, где их надо держать
// синхронными, и оно названо.
//
// Конечная остановка круга — `/app/today`: у неё нет ни права, ни модуля,
// она открыта каждому, кто вошёл. Инспектор (`compliance.read` без
// `stock.read`, 0035) и бухгалтер попадают именно туда.
export default async function AppEntry() {
  const m = await currentMembership()
  if (!m) redirect('/register/seller')

  if (can(m, 'stock.read') && hasModule(m, 'inventory')) redirect('/app/inventory')
  redirect('/app/today')
}
