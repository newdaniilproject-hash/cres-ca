import { notFound, redirect } from 'next/navigation'
import { createClient } from '@/lib/supabase/server'
import { currentMembership, can } from '@/lib/tenant'

export const dynamic = 'force-dynamic'

// ── Постійна адреса ЄМНОСТІ ─────────────────────────────────────────────────
//
// Заведена 25.08.2026 за вимогою власника: «при нажатии на пуш уведомление
// открывается карточка именно того предмета, о котором уведомление».
//
// До цього пуш про термін придатності вів на `/app/inventory` — увесь склад.
// Пояснення в `lib/notify/target.ts` було таке: у майстра зранку таких банок
// кілька, і список відповідає на питання цілком. Власник вирішив інакше,
// і його рішення точніше: сповіщення називає КОНКРЕТНУ банку з її кодом,
// а відкриває екран, де її ще треба знайти серед сотні позицій.
//
// ЧОМУ ОКРЕМИЙ МАРШРУТ, А НЕ АДРЕСА В ЧЕРЗІ. У черзі лежить `ref_id` —
// ідентифікатор ємності, і тільки він; екран же живе за адресою
// материнського засоба (`/materials/<materialId>/pao`). Класти повну адресу
// в чергу не можна з причини, вже названої в `lib/notify/target.ts`:
// нагадування ставиться сьогодні, а відкриється завтра, і заморожена
// адреса переживе будь-який переїзд розділу. Тому черга зберігає посилання
// на СУТНІСТЬ, а цей маршрут перетворює його на екран у момент натискання.
//
// Побічна користь названа окремо, щоб її не загубили: у банки з'явилась
// постійна адреса. Це те, що можна покласти в QR наліпки замість коду —
// але це окрема робота, і зараз наліпка друкує рядок бази без змін.
export default async function ContainerPage({
  params,
}: {
  params: Promise<{ id: string }>
}) {
  const { id } = await params
  const m = await currentMembership()
  if (!m) redirect('/register/seller')
  // Те саме право, що й на екрані, куди ведемо: PAO і вскриття — це
  // Техрегламент, а не склад. Інспектор сюди заходить законно.
  if (!can(m, 'compliance.read')) redirect('/app')

  const supabase = await createClient()
  // Читаємо через компланс-представлення, а не таблицю: інспектору
  // політика `material_containers` віддає рядки, а от `materials` — ні,
  // і прямий join мовчки повернув би порожнечу замість переходу
  // (та сама грабля, що закрита 0083).
  const { data } = await supabase
    .from('compliance_containers')
    .select('id, material_id')
    .eq('id', id)
    .maybeSingle()

  // Немає рядка — немає і переходу. Це не «ємність зникла»: RLS не віддала
  // її чужому закладу, і 404 тут чесніше за редирект у порожній екран.
  if (!data?.material_id) notFound()

  redirect(`/app/inventory/materials/${data.material_id}/pao`)
}
