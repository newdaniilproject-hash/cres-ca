import { getLang, getT } from '@/lib/i18n/server'
import { LangProvider } from '@/lib/i18n/client'

// Оболочка мобильного приложения. Сюда указывает capacitor.config.ts,
// и это НЕ страницы сайта: ни шапки, ни переключателя темы, ни ссылки
// «на головну» — в приложении их быть не должно.
//
// Общая логика (Supabase, права, серверные действия) та же самая, что в вебе.
// Различается только раскладка — ровно как требует правило проекта
// «общий слой вместо паритета».

// Заголовок вкладки — строка интерфейса, поэтому из словаря и через
// `generateMetadata`: обёртка показывает его в списке недавних вкладок
// и в переключателе приложений, и он обязан быть на языке человека.
export async function generateMetadata() {
  const t = await getT()
  return { title: t('m.meta.title') }
}

// Приложение не масштабируется жестами: это не веб-страница.
// viewport-fit=cover нужен, чтобы контент уходил под вырез, а отступы
// задавались через env(safe-area-inset-*), а не гадались.
export const viewport = {
  themeColor: '#f6f7f9',
  viewportFit: 'cover' as const,
  width: 'device-width',
  initialScale: 1,
  maximumScale: 1,
}

// ЯЗЫК ОБЁРТКИ. Все экраны `/m` клиентские, и до 16.08.2026 провайдер
// стоял только в макете кабинета — то есть приложение говорило
// по-украински независимо от выбора человека. Куку читаем на сервере:
// текст здесь есть в первом кадре, а клиентское значение приезжает
// вторым и мигало бы. Кэшем не платим — `/m` закрыт в `robots.ts`
// и живёт за входом.
export default async function MobileLayout({ children }: { children: React.ReactNode }) {
  const lang = await getLang()
  return (
    <LangProvider lang={lang}>
      <div
        className="m-frame flex flex-col"
        style={{
          // ── ВЫСОТА РАМКИ БОЛЬШЕ НЕ МЕНЯЕТСЯ НИКОГДА ────────────────
          //
          // Здесь по очереди перебывали: `minHeight: 100dvh` (dvh в веб-вью
          // не знает про клавиатуру), «100dvh минус вычисленная клавиатура»
          // (вычисление давало ноль), `var(--vvh)` от visualViewport
          // и `position: fixed` с поправкой на offsetTop. Каждое следующее
          // чинило предыдущее и приносило свой дефект.
          //
          // Общее у всех: рамка МЕНЯЛА РАЗМЕР, когда выезжала клавиатура.
          // А владелец 18.08.2026 сформулировал требование прямо:
          // «страница не должна вообще дёргаться». Меняющаяся высота — это
          // и есть дёрганье, каким бы точным ни был расчёт.
          //
          // Теперь высота постоянная: 100dvh, весь экран. Клавиатура
          // ложится ПОВЕРХ (`Keyboard.resize: 'none'` в capacitor.config.ts),
          // веб-вью не ужимается, перекладывать нечего. Сколько закрыто
          // снизу, знает `--kb` из `components/keyboard-fit.tsx`, и это
          // отступ ВНУТРИ прокручиваемой области, а не размер рамки.
          //
          // Заодно исчезает «чёрное полотно»: оно было местом, которое
          // освобождало ужавшееся веб-вью, и цвет там брался из бинаря.
          // Не ужимается — освобождать нечего.
          //
          // ⚠️ Анимировать эту высоту нельзя было и раньше (грабля
          // 12.08.2026: кольцо перерисовок убивало процесс веб-вью).
          // Теперь она просто константа, и вопрос закрыт.
          height: '100dvh',
          background: 'var(--color-bg)',
          paddingTop: 'env(safe-area-inset-top)',
          paddingBottom: 'env(safe-area-inset-bottom)',
          // Прокручивается содержимое внутри, а не сама рамка: иначе
          // экран «уезжает» целиком и шапка с кнопкой «Вийти» пропадает.
          overflow: 'hidden',
          // Свайп-назад по краю экрана не должен выделять текст.
          WebkitUserSelect: 'none',
          WebkitTapHighlightColor: 'transparent',
        }}
      >
        {children}
      </div>
    </LangProvider>
  )
}
