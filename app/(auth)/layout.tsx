import { getLang } from '@/lib/i18n/server'
import { LangProvider } from '@/lib/i18n/client'

// Макет заведён 16.08.2026 ради одного — ЯЗЫКА.
//
// Экраны входа, регистрации и восстановления целиком клиентские
// (`'use client'`, там формы и состояния), а провайдер языка стоял только
// в макете кабинета. Значит `useT()` здесь читал контекст с умолчанием
// и отдавал украинский ЛЮБОМУ: человек переключал язык в кабинете,
// выходил — и вход снова встречал его по-украински, включая отказы
// из `lib/auth-errors.ts`.
//
// Читаем куку на СЕРВЕРЕ, а не берём язык из корневого клиентского
// провайдера, потому что здесь текст есть в первом же кадре: заголовок,
// подписи полей, кнопка. Клиентское значение приезжает вторым кадром
// и дало бы вспышку украинского на русском интерфейсе — ровно то, ради
// чего тема и язык вообще ставятся синхронно (`lib/i18n/cookie.ts`).
//
// ЦЕНА: `cookies()` делает эти страницы динамическими — они перестают
// отдаваться из статического кэша. Плата принята осознанно: весь вход
// закрыт в `app/robots.ts` (`/login`, `/register`, `/reset`, `/forgot`),
// то есть ни одного поискового обхода здесь нет, а данных для кэша —
// одна форма. Витрина, где кэш действительно стоит денег, не затронута:
// корневой макет куку по-прежнему не читает.
export default async function AuthLayout({ children }: { children: React.ReactNode }) {
  return <LangProvider lang={await getLang()}>{children}</LangProvider>
}
