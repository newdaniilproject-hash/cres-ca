// Общий каркас и реквизиты для юридических страниц.
//
// Вынесено отдельно по одной причине: реквизиты владельца встречаются
// в политике, в порядке удаления данных и потом в оферте. Разъедутся —
// и документы начнут противоречить друг другу, что для юридического
// текста хуже, чем отсутствие текста.
//
// ── ПОЧЕМУ ТЕКСТ ЭТИХ ДОКУМЕНТОВ НЕ УЕЗЖАЕТ В СЛОВАРЬ ──────────────────────
//
// Политика конфиденциальности и порядок удаления данных — не экраны,
// а ОПУБЛИКОВАННЫЕ ДОКУМЕНТЫ с номером редакции и датой вступления в силу.
// Редакция уходит в журнал согласий: в оферте это `LEGAL_VERSION`
// из `lib/legal.ts`, который триггер `handle_new_user` кладёт
// в `user_consents`. Если одна и та же редакция начнёт отдаваться на трёх
// языках, запись «принял 2026-08-05» перестанет указывать на конкретный
// текст, а именно в этом весь смысл журнала (`lib/legal.ts`).
//
// Перевод юридического документа — это НОВАЯ РЕДАКЦИЯ: своя дата, своя
// версия, своя строка в журнале и заключение о том, что перевод совпадает
// по смыслу. Это решение владельца и юриста, а не побочный эффект правки
// экранов, поэтому здесь переводятся ПОДПИСИ ВОКРУГ документа (строка
// «Версія … Чинна з …») и не переводится он сам. То же правило уже
// применено в `components/legal.tsx` к оферте и политике cookie.
//
// Каркас `LegalDoc` в `components/legal.tsx` делает ровно то же самое,
// и держать два каркаса юридического документа — долг: они разойдутся
// по виду, и это первое, что замечает проверяющий из App Store.

// ⚠️ ЗАГЛУШКА. Юридическое лицо ещё не зарегистрировано — это блокер
