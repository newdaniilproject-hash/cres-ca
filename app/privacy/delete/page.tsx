import Link from 'next/link'
import { createClient } from '@/lib/supabase/server'
import { PublicHeader, PublicFooter, publicT as t } from '@/components/shell'
import { OWNER, POLICY_VERSION, POLICY_DATE, Legal, H2, P, Ul } from '../legal'

export const metadata = {
  title: 'Видалення даних',
  description:
    'Як видалити акаунт і персональні дані з платформи Маркет: способи, строки, що саме видаляється.',
}

// Data Deletion Instructions. Отдельная страница, а не абзац в политике,
// потому что Meta требует ровно «Data Deletion Instructions URL», Google
// Play — отдельную ссылку на удаление данных в карточке приложения,
// а App Store смотрит, что процедура описана и выполнима.
//
// Текст сознательно говорит и о том, что НЕ удаляется: журналы
// соответствия и первичные документы закон велит хранить, и обещать
// их стирание — значит обещать нарушение.
//
// Как и политика, это опубликованный документ с номером редакции, а не
// экран: в словарь уехала только подпись под ним. Обоснование — в шапке
// `../legal.tsx`. Отдельно: тема письма «Видалення акаунта» ЦИТИРУЕТСЯ
// в самом тексте документа («з теми …»), поэтому она остаётся здесь,
// а не в словаре — иначе тема и документ разъедутся на первом же
// переводе, и человек напишет письмо с темой, которой в инструкции нет.
export default async function DataDeletionPage() {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()

  return (
    <>
      <PublicHeader authed={!!user} />
      <Legal title="Видалення даних та акаунта">
        <P>
          Ви можете видалити свій обліковий запис і повʼязані з ним персональні
          дані у будь-який момент і без пояснення причин. Нижче — як саме,
          у які строки і що при цьому відбувається з даними, які закон
          зобовʼязує зберігати.
        </P>

        <H2>Спосіб 1. Написати нам</H2>
        <P>
          Надішліть лист на{' '}
          <a className="underline underline-offset-2" href={`mailto:${OWNER.email}?subject=${encodeURIComponent('Видалення акаунта')}`}>
            {OWNER.email}
          </a>{' '}
          з теми «Видалення акаунта». Лист має бути з тієї самої адреси, на яку
          зареєстровано акаунт — це єдиний спосіб пересвідчитися, що заявку
          подали саме ви, а не сторонній.
        </P>
        <P>
          Ми підтверджуємо отримання протягом 3 робочих днів і видаляємо дані
          протягом 30 днів. Окремих форм, дзвінків і пояснень причин не
          вимагаємо.
        </P>

        <H2>Спосіб 2. Якщо ви продавець — спочатку вивантажте дані</H2>
        <P>
          Клієнтська база, каталог і облікові записи закладу — ваша власність.
          Перед видаленням акаунта вивантажте їх: після видалення відновити
          дані буде неможливо. Вивантаження безкоштовне і не обмежене
          кількістю разів.
        </P>
        <P>
          Видалення акаунта власника закладу зупиняє роботу вітрини та кабінету
          для всіх співробітників цього закладу. Якщо ви хочете піти з команди,
          але не закривати заклад — попросіть власника виключити вас зі складу
          команди: тоді ваш акаунт залишиться, а доступ до даних закладу
          припиниться того ж дня.
        </P>

        <H2>Що саме видаляється</H2>
        <Ul items={[
          'обліковий запис: пошта, імʼя, телефон, фото профілю, налаштування;',
          'сеанси входу — усі пристрої відразу;',
          'звʼязок вашого акаунта із закладами, у яких ви працювали;',
          'адреса і контакти в оформлених вами замовленнях знеособлюються.',
        ]} />

        <H2>Що залишається і чому</H2>
        <P>
          Частина записів не видаляється на вимогу — не з нашої примхи, а тому
          що закон вимагає їх зберігати. Ці записи знеособлюються: із них
          прибираються ваші контактні дані, але сам факт операції лишається.
        </P>
        <Ul items={[
          <>
            <b>Первинні документи і фінансові записи</b> — у строки, встановлені
            податковим законодавством України.
          </>,
          <>
            <b>Санітарні журнали, партії, терміни придатності та журнал дій</b> —
            це доказова база закладу перед контролюючими органами
            (Держпродспоживслужба, Держлікслужба). Вони незмінювані за своєю
            природою: журнал, з якого можна щось прибрати, не є доказом.
          </>,
          <>
            <b>Записи, необхідні для вирішення спору</b> — якщо на момент
            звернення триває спір щодо замовлення, дані зберігаються до його
            завершення.
          </>,
        ]} />

        <H2>Якщо ви клієнт закладу, а не користувач Платформи</H2>
        <P>
          Коли ви записувалися до майстра або замовляли товар без реєстрації,
          володільцем ваших даних є сам заклад, а Платформа лише обробляє їх
          за його дорученням. Вимогу про видалення в такому разі адресуйте
          закладу — його контакти є на сторінці закладу. Якщо заклад не
          відповідає, напишіть нам: ми зобовʼязані передати йому вашу вимогу
          і повідомити вас про результат.
        </P>

        <H2>Якщо щось пішло не так</H2>
        <P>
          Якщо ми не відповіли у строк або ви вважаєте відповідь
          необґрунтованою, ви маєте право звернутися до Уповноваженого
          Верховної Ради України з прав людини, а мешканці ЄС — до наглядового
          органу своєї країни.
        </P>

        <P>
          Повний перелік того, які дані ми обробляємо і навіщо, —
          у <Link className="underline underline-offset-2" href="/privacy">політиці конфіденційності</Link>.
        </P>

        <p className="t-sm mt-10 prose-muted">
          {t('public.legal.version', {
            version: POLICY_VERSION,
            date: t.date(POLICY_DATE, { day: 'numeric', month: 'long', year: 'numeric' }),
          })}{' '}
          {t('public.legal.owner', { name: OWNER.name, address: OWNER.address })}
        </p>
      </Legal>
      <PublicFooter />
    </>
  )
}
