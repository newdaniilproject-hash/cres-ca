-- 0034 — владелец отсутствовал в role_grants, и из-за этого молчали ВСЕ уведомления
-- у любого заведения, где владелец работает один. То есть у первого платящего клиента.
--
-- КАК НАШЛОСЬ. 14.08.2026 демо-арендатора наполнили данными под показ: вскрыли две
-- ёмкости так, чтобы срок истекал через 5 и через 13 дней — ровно под пороги 7 и 14.
-- Триггер отработал, use_by посчитался правильно, а в notification_outbox не появилось
-- НИ ОДНОЙ строки cosmetics.expiry_7d / expiry_14d.
--
-- ПРИЧИНА. role_grants объявлен источником правды по правам, но строк для роли owner
-- в нём нет ни одной: 18 у admin, 14 у manager, 7 у operator, 4 у accountant,
-- 5 у viewer, 3 у inspector, 0 у owner. Владелец получает права спецкейсом внутри
-- custom_access_token_hook: `when tm.role = 'owner' then '["*"]'`. В токене это
-- работает — а в SQL нет. enqueue_expiry_warnings и enqueue_staff_alert ищут
-- получателей запросом
--   exists (select 1 from role_grants rg
--            where rg.role = tm.role and rg.permission = 'stock.read')
-- и для owner он не находит ничего. Список получателей пуст, рассылка тихо
-- завершается успехом, очередь остаётся пустой.
--
-- ПОЧЕМУ ЭТО НЕ ЗАМЕТИЛИ. Шаблоны cosmetics.expiry_7d и expiry_14d в базе есть
-- и выглядят готовыми. Функции есть. Триггер есть. Всё «сделано» — и ничего не работает.
-- Ровно тот случай, ради которого в этом проекте заведено правило проверять
-- исполнением, а не наличием.
--
-- ЧЕМ ЭТО ГРОЗИЛО. «Попередження про кінець терміну за 14/7 днів» — обещание лендинга
-- и одна из двух причин, по которым салон вообще платит за комплаенс. Оно не
-- исполнялось бы ни у демо, ни у клиента, пока тот не заведёт второго сотрудника
-- с ролью ниже владельца. Заметили бы после первой проверки СЕС, то есть поздно.
--
-- РЕШЕНИЕ. Привести источник правды в соответствие с тем, что и так выдаётся в токене:
-- владелец получает все права, какие вообще существуют в системе. Берём объединение
-- прав всех ролей, а не список руками — иначе следующая новая привилегия снова
-- обойдёт владельца стороной, и мы вернёмся сюда через полгода.
insert into public.role_grants (role, permission)
select 'owner'::public.member_role, rg.permission
  from (select distinct permission from public.role_grants) rg
on conflict do nothing;

-- Проверка смысла, а не факта вставки: у владельца обязано стать прав не меньше,
-- чем у самой полной из остальных ролей. Если это не так — вставка прошла криво,
-- и лучше уронить миграцию здесь, чем узнать об этом от клиента.
do $$
declare
  v_owner integer;
  v_max_other integer;
begin
  select count(*) into v_owner
    from public.role_grants where role = 'owner';

  select max(c) into v_max_other
    from (select count(*) as c from public.role_grants
           where role <> 'owner' group by role) s;

  if v_owner < v_max_other then
    raise exception 'owner получил % прав, а самая полная из прочих ролей имеет % — вставка неверна',
      v_owner, v_max_other;
  end if;
end
$$;

