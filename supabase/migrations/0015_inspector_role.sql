-- 0015_inspector_role.sql
-- Права роли «инспектор» — проверяющий из ТЗ салона (Inspector View).
--
-- Отдельный файл не по прихоти: Postgres запрещает использовать новое
-- значение перечисления в той транзакции, где оно создано. Значение
-- 'inspector' добавлено в 0014, здесь оно наполняется правами.
--
-- Инспектор видит: реестр косметики и материалов, партии и сроки,
-- журналы дезинфекции/уборки/стерилизации, техкарты (compliance.read),
-- сам каталог позиций (catalog.read — чтобы читать названия услуг
-- в техкартах) и склад БЕЗ денег (stock.read: остатки и движения,
-- но представление «сколько денег на полках» отдаёт только строки
-- своих магазинов с ценами — инспектору они видны; это осознанно:
-- остатки в штуках инспектору нужны для сверки с реестром).
--
-- Инспектор НЕ видит: клиентов, заказы, финансы, настройки, команду.
-- Писать не может ничего: у него нет ни одного *.write.
--
-- Приглашается штатно: tenant_members с ролью inspector на время
-- проверки, по окончании — исключение из команды (сеансы завершаются
-- принудительно, docs/DOMAIN.md).

insert into public.role_grants (role, permission) values
  ('inspector','compliance.read'),
  ('inspector','catalog.read'),
  ('inspector','stock.read');
