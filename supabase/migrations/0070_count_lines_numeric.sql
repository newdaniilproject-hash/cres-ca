-- ===========================================================================
-- 0070. Инвентаризация расходников считает дробями, а не штуками
-- ===========================================================================
--
-- 0066 разрешил ставить расходники в документ пересчёта, но обе величины
-- строки остались целыми — `expected_qty int`, `counted_qty int`. Для товара
-- это верно: футболок не бывает две с половиной. Для расходника — неверно
-- всегда: `materials.unit` это «г», «мл», «м», а `current_stock` numeric.
--
-- Что происходило молча. Пузырёк осветлителя, в котором осталось 0.5 л,
-- попадал в строку как `expected_qty = 0` (Postgres приводит numeric к int
-- округлением). Мастер вписывал факт — тоже целым — и документ рождал
-- расхождение из ниоткуда: движение «коригування» на 1 единицу там, где
-- ничего не менялось. Остаток при этом сходился с журналом, то есть
-- сверка кэша ошибку НЕ ловила: журнал послушно записал ложь.
--
-- Одна инвентаризация склада из полусотни банок — это полсотни ложных
-- корректировок в журнале, который по Техрегламенту предъявляют инспектору
-- и который нельзя переписать. Поэтому правится до первой инвентаризации
-- у клиента, а не после.
--
-- numeric без указания точности — тот же тип, что у `materials.current_stock`
-- и у `stock_movements.quantity`. Совпадение типов здесь важнее «красивой»
-- точности вроде numeric(14,3): разъехавшиеся масштабы дают округление
-- на стыке, а именно на этом стыке считается расхождение.
-- ===========================================================================

alter table public.stock_count_lines
  alter column expected_qty type numeric,
  alter column counted_qty  type numeric;

-- Остаток не бывает отрицательным ни у товара, ни у расходника, а «минус
-- две банки на полке» — это опечатка в вводе, а не находка инвентаризации.
-- Расхождение при этом уйти в минус может: на то оно и расхождение.
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'stock_count_lines_qty_nonneg') then
    alter table public.stock_count_lines
      add constraint stock_count_lines_qty_nonneg
      check (expected_qty >= 0 and (counted_qty is null or counted_qty >= 0));
  end if;
end $$;

-- Ссылка на materials появилась в 0066 без своего индекса: частичный
-- уникальный по (count_id, material_id) для поиска ПО материалу не годится —
-- ведущая колонка другая. Без этого индекса удаление расходника сканирует
-- все строки всех пересчётов, а `on delete restrict` заставляет базу делать
-- это на каждую попытку.
create index if not exists stock_count_lines_material_idx
  on public.stock_count_lines (material_id) where material_id is not null;

comment on column public.stock_count_lines.expected_qty is
  'Снимок остатка на момент start_stock_count. numeric, а не int: у расходника '
  'единица измерения — грамм или миллилитр, и половина банки это 0.5, а не 0.';
comment on column public.stock_count_lines.counted_qty is
  'Факт с полки; null — ещё не считали. Ноль и «не считали» это разные вещи: '
  'первое проведёт списание в ноль, второе не тронет позицию вовсе.';
