-- 0040 — данные, которых требует ТЗ, но которых в базе не было.
--
-- 1. ТЕХКАРТА ПІДГОТОВКИ КАНЕКАЛОНУ.
-- ЧТО БЫЛО. Раздел 3.4 ТЗ требует именно регламент подготовки волокна.
-- В tech_cards лежала одна карта — «Афрокоси, зачіска на 4 години», 8 шагов,
-- и ни в одном из них нет ни вымачивания, ни раствора, ни выдержки: карта
-- описывает работу с уже готовым волокном. То есть требование ТЗ в базе
-- не покрыто ничем.
-- ЧЕМ ГРОЗИЛО. Необработанный канекалон — самая частая причина раздражения
-- кожи головы у клиента. Регламент подготовки — это то, чем салон
-- оправдывается, если претензия дошла до проверки. Пустое место в техкартах
-- означает «регламента нет», а не «регламент устный».
-- ЧТО СТАЛО. Карта из 8 шагов: осмотр и фиксация партии, содовый раствор
-- (пропорция, температура, объём), вымачивание с выдержкой, полоскание,
-- кондиционирование с пропорцией и выдержкой, сушка, хранение.
-- Пропорции и время лежат отдельными ключами steps (solution, proportion,
-- temperature_c, hold_minutes, minutes), а не только текстом, чтобы интерфейс
-- мог показать таймер, а не абзац.
--
-- ЧЕСТНО О ДВУХ ДОПУЩЕНИЯХ:
--   а) Нулевым шагом идёт прямое указание: пропорции и выдержку сверить
--      с рекомендацией производителя конкретного канекалона, и при расхождении
--      завести НОВУЮ версию карты. Это не отговорка, а единственный
--      правильный порядок: tech_cards_guard запрещает править steps
--      утверждённой версии, и обойти его подгонкой цифр не выйдет.
--   б) approved_by — колонка NOT NULL, поэтому карту нельзя завести «ничьей».
--      Проставлен владелец арендатора: он и есть ответственное лицо, которое
--      по ТЗ отвечает за регламенты. Владелец обязан карту прочитать;
--      если он с ней не согласен — снимает is_active и заводит версию 2.
--
-- 2. ЗАДАЧА «КВАРЦЮВАННЯ».
-- ЧТО БЫЛО. В cleaning_tasks четыре задачи: влажная уборка, генеральная,
-- дезинфекция кресла, стерилизация инструмента. Кварцевания — обеззараживания
-- воздуха бактерицидной лампой — не было, хотя это отдельная строка санитарных
-- требований к помещению и отдельная запись в журнале.
-- ЧТО СТАЛО. Задача с расписанием «щодня, після закриття, 30 хв» и прямым
-- указанием фиксировать время включения и выключения: проверяющего интересует
-- не факт наличия лампы, а длительность цикла.
--
-- ОБА ВСТАВЛЕНИЯ ИДЕМПОТЕНТНЫ (where not exists по названию) и выполняются
-- для каждого арендатора, а не для одного захардкоженного uuid.
--
-- ПРОВЕРЕНО ИСПОЛНЕНИЕМ (в транзакции с откатом): в tech_cards стало 2 карты,
-- у новой 8 шагов и заполненный approved_by; в cleaning_tasks стало 5 задач;
-- обе вставки попали в audit_log с правильными label — то есть аудит
-- справочников работает и на новых данных.

insert into public.tech_cards (tenant_id, title, version, steps, is_active, approved_by)
select t.id, 'Підготовка (вимочування) канекалону перед плетінням', 1,
  jsonb_build_array(
    jsonb_build_object('step',0,'title','Перед роботою','detail','Пропорції та витримку звірити з рекомендацією виробника конкретного канекалону. Якщо виробник дає інші значення — завести НОВУ версію техкарти, а не правити цю.'),
    jsonb_build_object('step',1,'title','Огляд і фіксація партії','detail','Перевірити цілісність упаковки, колір, партію. Зафіксувати партію та дату розпакування в журналі.','minutes',5),
    jsonb_build_object('step',2,'title','Содовий розчин','detail','Харчова сода у теплій воді 40-45 C. Об''єм з розрахунку 3 л на пачку 100 г.','solution','сода харчова','proportion','15 г (1 ст. л.) на 1 л води','temperature_c',45,'minutes',5),
    jsonb_build_object('step',3,'title','Вимочування','detail','Занурити пасма повністю, розправити. Витримка 20 хвилин. Понад 30 хвилин не тримати — волокно втрачає форму.','hold_minutes',20,'minutes',20),
    jsonb_build_object('step',4,'title','Полоскання','detail','Промити проточною водою 20-25 C у 2-3 зміни води, доки не зникне слизькість.','minutes',5),
    jsonb_build_object('step',5,'title','Кондиціонування','detail','Розчин бальзаму-кондиціонера, витримка 3 хвилини, потім ретельно змити.','solution','бальзам-кондиціонер','proportion','1:10','hold_minutes',3,'minutes',5),
    jsonb_build_object('step',6,'title','Сушіння','detail','Відтиснути рушником без викручування, підвісити до повного природного висихання 3-6 годин. Фен, батарея, пряме сонце заборонені.','minutes',240),
    jsonb_build_object('step',7,'title','Зберігання','detail','Підготовлене волокно тримати в закритому пакеті з підписом партії та дати не довше 7 діб.')
  ), true, tm.user_id
  from public.tenants t
  join lateral (
        select m.user_id from public.tenant_members m
         where m.tenant_id = t.id and m.role = 'owner'
         order by m.created_at limit 1
       ) tm on true
 where not exists (
   select 1 from public.tech_cards tc
    where tc.tenant_id = t.id
      and tc.title = 'Підготовка (вимочування) канекалону перед плетінням');

insert into public.cleaning_tasks (tenant_id, name, schedule, position, is_active)
select t.id, 'Кварцювання приміщення бактерицидною лампою',
       'Щодня, після закриття, 30 хв (у журналі — час увімкнення та вимкнення)', 10, true
  from public.tenants t
 where not exists (
   select 1 from public.cleaning_tasks c
    where c.tenant_id = t.id
      and c.name = 'Кварцювання приміщення бактерицидною лампою');
