-- ===========================================================================
-- 0072. Два отступления от правил 3 и 7, найденные анализатором Supabase
-- ===========================================================================
--
-- Проверка запущена 15.08.2026 после перехода на Pro. Из 61 замечания
-- 54 разобраны и законны (представления соответствия работают правами
-- владельца намеренно — 0062; восемь анонимных точек объявлены в CLAUDE.md).
-- Осталось два, и оба настоящие.
--
-- ── А. stock_value_view ПОТЕРЯЛА security_invoker. Регрессия из 0066 ──────
--
-- 0009 завела оба складских представления с `security_invoker = true`:
-- политики применяются к тому, КТО СМОТРИТ, а не к тому, кто создал.
-- Без этого флага представление читает таблицы правами владельца, то есть
-- МИМО RLS, — ровно тот «обход», который запрещает правило 3.
--
-- 0066 переписала stock_value_view через `create or replace view`, чтобы
-- добавить расходники, и флаг не повторила. `create or replace` сохраняет
-- не все настройки: security_barrier уцелел, security_invoker — нет.
-- Соседняя stock_low_view осталась с флагом, и расхождение видно запросом
-- к pg_class: одна `true`, другая «не задано».
--
-- Чем это грозило: у представления есть колонка tenant_id, и приложение
-- фильтрует по ней. Но без RLS `select * from stock_value_view` вернул бы
-- строки ВСЕХ арендаторов — стоимость склада, себестоимость, количество
-- позиций. Для мультиарендной платформы это утечка первого рода.
--
-- Почему не выстрелило: в базе сейчас один арендатор и ноль строк
-- в представлении. То есть дефект был бы обнаружен ВТОРЫМ клиентом,
-- а не проверкой. Это ровно тот случай, ради которого список 1 плана
-- стоит перед первой продажей.
--
-- ── Б. Триггерные функции доступны анониму ────────────────────────────────
--
-- Правило 7: каждая функция в миграции заканчивается явным revoke/grant,
-- потому что Postgres выдаёт EXECUTE роли PUBLIC на каждую новую функцию,
-- а Supabase поверх этого раздаёт права ролям anon и authenticated
-- через `alter default privileges`.
--
-- Пять функций это правило нарушили. Три из них — мои, сегодняшние:
--   stock_movement_guard, stock_receipt_guard  (0066)
--   batches_notify                             (0067)
-- Ещё две — более ранние:
--   containers_propagate_use_by
--   my_account_files_count (0057 сняла права у PUBLIC, но не у ANON —
--     это та самая ловушка Supabase, описанная в CLAUDE.md, и 0057
--     наступила на неё ровно так же, как 0060)
--
-- Практический риск невелик: триггерную функцию, вызванную напрямую,
-- Postgres роняет («can only be called as a trigger»), а
-- my_account_files_count у анонима считает по auth.uid() = null и вернёт 0.
-- Но правило написано не про «сработает ли прямо сейчас», а про то, что
-- лишнее право живёт до первой ошибки в теле функции. Убираем.
--
-- Триггеры от этого не пострадают: Postgres не проверяет EXECUTE при
-- срабатывании триггера — он выполняется правами владельца таблицы.
-- ===========================================================================

-- ── А ──────────────────────────────────────────────────────────────────────

alter view public.stock_value_view set (security_invoker = true);

-- Барьер оставляем: он не даёт планировщику протащить пользовательское
-- условие внутрь представления раньше проверки политик.
alter view public.stock_value_view set (security_barrier = true);

-- Представление о доступе команды анониму не нужно ни в каком виде.
-- Права ему достались тем же умолчанием Supabase, а не решением.
revoke all on public.team_access_log from anon;

comment on view public.stock_value_view is
  'Стоимость склада по арендаторам. security_invoker = true ОБЯЗАТЕЛЕН: без него '
  'представление читает мимо RLS и показывает чужих арендаторов. Потерян в 0066, '
  'возвращён в 0072 — при create or replace флаг не сохраняется, повторять явно.';

-- ── Б ──────────────────────────────────────────────────────────────────────

revoke all on function public.stock_movement_guard()        from public, anon, authenticated;
revoke all on function public.stock_receipt_guard()         from public, anon, authenticated;
revoke all on function public.batches_notify()              from public, anon, authenticated;
revoke all on function public.containers_propagate_use_by() from public, anon, authenticated;

-- Эта — не триггерная: её зовёт экран удаления аккаунта, значит
-- authenticated право нужно. Анониму — нет.
revoke all   on function public.my_account_files_count() from public, anon;
grant execute on function public.my_account_files_count() to authenticated;
