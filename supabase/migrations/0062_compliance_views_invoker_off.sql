-- 0062. Откат security_invoker, включённого в 0061 на боевой базе.
--
-- ОШИБКА. Пересоздавая представления в 0060 и наводя порядок в правах
-- в 0061, я заодно включил security_invoker: «пусть RLS исходных таблиц
-- будет вторым рубежом». Рассуждение красивое и неверное.
--
-- ПОЧЕМУ НЕВЕРНОЕ. Эти представления существуют ровно затем, чтобы
-- ОБОЙТИ RLS исходных таблиц: инспектор по 0035 имеет только
-- compliance.read, а политика materials требует stock.read. С включённым
-- security_invoker кабинет инспектора перестал бы показывать реестр
-- вообще — экран был бы пуст, и это читалось бы как «данных нет»,
-- а не как отказ в правах. Дефект того же рода, что и все остальные
-- в этом проекте: выглядит рабочим, молча врёт.
--
-- Граница доступа у этих представлений — их собственный where
-- (tenants_with('compliance.read')) плюс права: authenticated получает
-- ТОЛЬКО select, что и сделано в 0061.
--
-- Здесь опция выставляется явно, а не «оставляется по умолчанию»:
-- при повторном прогоне с нуля представление и так создаётся с invoker
-- off, но явная строка не даёт молча включить его снова.

alter view public.compliance_materials  set (security_invoker = off);
alter view public.compliance_batches    set (security_invoker = off);
alter view public.compliance_containers set (security_invoker = off);
