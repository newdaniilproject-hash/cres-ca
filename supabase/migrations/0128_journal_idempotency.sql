-- 0128. Ключ ідемпотентності для трьох санітарних журналів.
--
-- ── ЩО САМЕ ЗЛАМАНО ────────────────────────────────────────────────────────
--
-- Правило проекту сформульоване і записане в CLAUDE.md: «в очередь уходит
-- ключ идемпотентности, сгенерированный ЭКРАНОМ до первой попытки». Аудит
-- 25.08.2026 показав, що воно виконане РІВНО В ОДНОМУ місці — `newKey()`
-- у всьому застосунку викликається один раз, у розливі (0100). Три
-- санітарні журнали досилаються з офлайн-черги голим INSERT:
--
--   lib/offline/queue.ts → journal.cleaning / .sterilization / .solution
--
-- ── ЧОМУ ЦЕ ГІРШЕ, НІЖ ЗДАЄТЬСЯ ────────────────────────────────────────────
--
-- Сценарій той самий, заради якого правило й писалось: майстер відмічає
-- дезінфекцію, запит доходить до бази, транзакція комітиться, а ВІДПОВІДЬ
-- не доїжджає — Wi-Fi біля крісла. Клієнт бачить мережеву помилку, кладе
-- дію в чергу, і при появі мережі вставляє ДРУГИЙ рядок.
--
-- І видалити його не можна ніколи: на всіх трьох таблицях стоїть
-- `journal_guard` на BEFORE UPDATE OR DELETE, політик UPDATE/DELETE немає.
-- Заклад назавжди лишається з рядком «дезінфекція виконана двічі о 14:32»
-- у документі, який несуть на перевірку. Тобто механіка, що мала захищати
-- журнал, псує саме його — і саме тим, що він чесний.
--
-- ── ЧОМУ УНІКАЛЬНЕ ОБМЕЖЕННЯ, А НЕ `on conflict do nothing` ────────────────
--
-- Могло здатись, що досить `upsert(..., ignoreDuplicates)`. Але нам треба,
-- щоб ПОВТОР БУВ ПОМІТНИЙ КОДУ: черга має відрізнити «вставив» від «воно
-- вже там». `on conflict do nothing` повертає порожньо в обох випадках
-- рівно однаково — і тоді відсутність рядка через RLS теж виглядає як
-- успіх. Унікальне обмеження дає 23505, і черга читає його однозначно:
-- «дія вже зафіксована, знімаю з черги».
--
-- Індекс ЧАСТКОВИЙ (`where idempotency_key is not null`) з двох причин:
-- записи, зроблені онлайн і зі старих версій застосунку, ключа не мають
-- і не повинні конфліктувати між собою; і колонка додається до таблиці,
-- де вже є рядки, — обмеження на всі рядки не встало б.
--
-- Міграція ДОДАЮЧА: колонка nullable, індекс частковий. Розгорнутий
-- застосунок, який ключа не шле, працює як раніше.

alter table public.cleaning_entries      add column if not exists idempotency_key text;
alter table public.sanitation_solutions  add column if not exists idempotency_key text;
alter table public.sterilization_cycles  add column if not exists idempotency_key text;

comment on column public.cleaning_entries.idempotency_key is
  'Ключ, згенерований ЕКРАНОМ до першої спроби. Захищає від подвоєння '
  'при досилці з офлайну: відповідь могла не доїхати після коміту.';

create unique index if not exists cleaning_entries_idem_key
  on public.cleaning_entries (tenant_id, idempotency_key)
  where idempotency_key is not null;

create unique index if not exists sanitation_solutions_idem_key
  on public.sanitation_solutions (tenant_id, idempotency_key)
  where idempotency_key is not null;

create unique index if not exists sterilization_cycles_idem_key
  on public.sterilization_cycles (tenant_id, idempotency_key)
  where idempotency_key is not null;

-- ── Де перевіряється, що це працює ─────────────────────────────────────────
--
-- Не тут. Правило проекту: «запрет проверяется ПОПЫТКОЙ его нарушить»,
-- а спроба потребує справжнього користувача (`performed_by` посилається
-- на `auth.users`). Заводити користувача в схемі `auth` з міграції, що
-- накочується на бій, не можна — це не наша таблиця.
--
-- Тому перевірка живе там, де їй місце: `supabase/tests/45_journal_idem.sql`
-- накочує все з нуля, заводить орендаря й користувача і двічі вставляє
-- той самий ключ, вимагаючи відмови. Перша версія цієї міграції несла
-- перевірку в собі й одразу впала на цьому ж зовнішньому ключі — добре,
-- що впала на стенді, а не на бою.
