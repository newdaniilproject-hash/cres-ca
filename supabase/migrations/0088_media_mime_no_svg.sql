-- ===========================================================================
-- 0088. Бакет `media` больше не принимает SVG.
-- ===========================================================================
--
-- ЧТО БЫЛО. 0019 завела `media` с
--   image/jpeg, image/png, image/webp, image/avif, image/gif, image/svg+xml
-- Последний тип — хранимая XSS, а не формат картинки, и вот почему именно
-- в этом бакете:
--
--   • `media` ПУБЛИЧНЫЙ и раздаётся с CDN без подписи (так решено в 0019
--     ради бюджета отрисовки, правило 6). Значит файл открывается прямым
--     адресом на домене хранилища проекта;
--   • SVG — это XML-документ, а не растр. Внутри законно живут `<script>`,
--     `<foreignObject>` и `onload`. Открытый по прямой ссылке, он
--     исполняется как страница НА ДОМЕНЕ ХРАНИЛИЩА — то есть получает
--     доступ к тому, что этот домен хранит для пользователя;
--   • загрузку в `media` может сделать любой участник заведения с правом
--     `catalog.write` (политики 0019). Это не «доверенная зона»: продавцов
--     будут тысячи, и один из них может быть недобросовестным.
--
-- ПОЧЕМУ ЭТО НЕ ЛОМАЕТ НИ ОДНОГО ЭКРАНА. Сверено с кодом загрузки:
-- единственное место, кладущее файлы в `media`, — форма фото товара
-- (`app/app/catalog/offering-form.tsx`), и она принимает ровно
-- `MEDIA_EXT_BY_MIME` из `lib/upload/guard.ts`: jpeg, png, webp, avif, gif.
-- SVG там не принимается уже сейчас, и в шапке `guard.ts` прямо написано,
-- что убрать его из самого бакета должен владелец `supabase/**`. Логотипы
-- заведения и аватары мастеров сегодня не загружает ни один экран вовсе.
--
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ. Она не удаляет уже лежащие SVG. На бою
-- их нет (в `media` вообще ничего не лежало на 17.08.2026), а писать
-- удаление файлов в миграцию, которая может однажды примениться на базе
-- с данными, — способ потерять чужое.
--
-- ПРОВЕРКА ВТОРОГО БАКЕТА. `documents` пересмотрен целиком и остаётся
-- как есть:
--   pdf, jpeg, png, webp, doc, docx — ровно `DOC_EXT_BY_MIME` из
--   `guard.ts`, то есть ровно то, что грузят оба экрана документов.
-- SVG и HTML там нет. Опасность «документа со скриптом» в нём и так
-- ниже: бакет приватный, отдаётся только подписанной ссылкой и только
-- по праву `compliance.read`. Сужать нечего, расширять не за чем.
--
-- Напоминание о границе: `allowed_mime_types` сверяет ЗАЯВЛЕННЫЙ клиентом
-- Content-Type. Настоящий тип по первым байтам проверяет
-- `/api/uploads/verify`. Одно другого не заменяет: бакет отсекает
-- запросы мимо формы, роут — подделку содержимого.

update storage.buckets
   set allowed_mime_types = array[
         'image/jpeg', 'image/png', 'image/webp', 'image/avif', 'image/gif']
 where id = 'media';

-- `documents` трогаем только приведением к тому же явному списку, чтобы
-- база с ручной правкой в панели вернулась к описанному в репозитории
-- состоянию. Значения те же, что в 0019.
update storage.buckets
   set allowed_mime_types = array[
         'application/pdf', 'image/jpeg', 'image/png', 'image/webp',
         'application/msword',
         'application/vnd.openxmlformats-officedocument.wordprocessingml.document']
 where id = 'documents';
