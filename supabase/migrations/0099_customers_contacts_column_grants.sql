-- ===========================================================================
-- 0099. Контакты клиента отдавались в обход маскировки. Догоняющая к 0090.
-- ===========================================================================
--
-- КАК НАШЛОСЬ. Разбором мест утечки при подключении журнала доступа к экрану
-- клиентов (шаг 7, пункт А). Запросом к политикам:
--
--   customers_read [select] using (tenant_id in (select tenants_with('customers.read')))
--
-- То есть колонки `phone` и `email` таблицы `customers` отдаются КАЖДОМУ,
-- у кого есть `customers.read`. Права `customers.contacts` на этом пути нет
-- вовсе — оно проверяется только в `v_bookings` (0078) и в `customer_card`
-- с `customers_export` (0090).
--
-- ЧЕМ ЭТО ГРОЗИЛО. Роль `viewer` имеет `customers.read` и НЕ имеет
-- `customers.contacts`. Экран показывал ему карточку с замаскированным
-- телефоном — а один запрос к PostgREST
--
--   GET /rest/v1/customers?select=name,phone,email
--
-- отдавал ту же базу целиком и в открытом виде. Плюс мимо журнала доступа:
-- ни строки «viewed», ни строки «exported». То есть обе защиты, ради которых
-- написана 0090, обходились адресной строкой.
--
-- ПОЧЕМУ ПРАВА НА КОЛОНКУ, А НЕ ПРЕДСТАВЛЕНИЕ. Колонку в RLS не скроешь:
-- политика фильтрует строки, а не поля (это же соображение записано в шапке
-- 0035). Дальше было два пути. Представление `v_customers` с маскировкой —
-- это ещё один объект, ещё одни права и ещё одно место, где надо помнить
-- про `customers.contacts`. Права на колонку — одна строка, действует
-- на любой путь к таблице сразу и не создаёт второго источника правды.
--
-- ПОЧЕМУ ЭТО НИЧЕГО НЕ ЛОМАЕТ. Проверено по коду: `customers` читается
-- из приложения ровно в одном месте — `app/app/customers/page.tsx`, — и там
-- список колонок явный и без контактов (та же правка, что и эта миграция).
-- Все, кому контакты нужны по делу, ходят через SECURITY DEFINER-функции
-- (`customer_card`, `customers_export`, `bookings_notify`, `create_order`,
-- `customers_stats_refresh`): владелец функции — не `authenticated`, права
-- на колонку его не касаются.
--
-- ЧТО ОСТАЁТСЯ ДОСТУПНЫМ. Всё остальное: имя, счётчики, суммы, дата
-- последнего заказа, метки, заметка. Список клиентов работает как работал.
--
-- ⚠️ ЭТО ПРАВКА СОСЕДНЕГО МОДУЛЯ (клиенты), сделанная из модуля журнала
-- доступа, и она названа отдельно — как требует правило «один модуль за раз».
-- Без неё журнал доступа остаётся украшением: он честно пишет, кто открыл
-- карточку, при том что базу можно унести, не открывая ни одной.
-- ===========================================================================

-- Право на колонку не отзывается «частично»: сначала снимаем SELECT
-- на таблицу целиком, потом выдаём его поимённо на всё, кроме контактов.
-- Порядок обратный сломал бы список клиентов.

revoke select on public.customers from anon;
revoke select on public.customers from authenticated;

grant select (
  id, tenant_id, user_id, name, note, tags,
  orders_count, total_spent, last_order_at, created_at, updated_at
) on public.customers to authenticated;

comment on column public.customers.phone is
  'Контакт клиента. Прямое чтение закрыто в 0099: телефон отдают только customer_card и customers_export, и обе пишут строку в журнал доступа и проверяют право customers.contacts.';
comment on column public.customers.email is
  'Контакт клиента. Прямое чтение закрыто в 0099 — см. комментарий к phone.';
