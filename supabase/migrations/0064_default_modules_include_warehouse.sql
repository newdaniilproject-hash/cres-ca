-- 0064. Новый заклад заводился БЕЗ склада и без журналов.
--
-- КАК НАШЛОСЬ. Владелец зарегистрировался, открыл кабинет и не увидел
-- раздела «Склад» вовсе. Экраны при этом были собраны и лежали на проде.
--
-- ПРИЧИНА. Колонка tenants.modules имела значение по умолчанию
--   {catalog, orders, customers, storefront}
-- — набор маркетплейса, из которого этот код вырос. register_tenant
-- модули не задаёт вовсе, поэтому каждый новый заклад получал именно его.
-- Оболочка кабинета прячет раздел, которого нет в modules (правило
-- «модуль — это что бизнес купил»), и склад с журналами не показывались
-- никому из вновь зарегистрированных.
--
-- ЧЕМ ЭТО БЫЛО. Продукт продаётся как «CRESKO — склад для майстрів»,
-- а склад в нём по умолчанию выключен. Первый же платящий клиент
-- не увидел бы того, за что заплатил, и решил бы, что продукта нет.
-- Дефект того же рода, что и остальные в этом проекте: всё написано,
-- собрано, задеплоено — и молча не работает.
--
-- ЧТО СТАЛО. Умолчание описывает продукт, а не его происхождение:
--   inventory   — склад, расходники, ёмкости, PAO и розлив;
--   compliance  — санитарные журналы, документы, техкарты, инспектор;
--   catalog     — товары и услуги, к ним привязана рецептура списания;
--   orders      — заказы (решение владельца 15.08.2026);
--   customers   — клиенты (решение владельца 15.08.2026);
--   storefront  — публичная страница, к которой ведёт «До публікації».
--
-- Финансы и маркетинг в умолчание НЕ входят: они вне оплаченной области
-- и подключаются отдельно. Это не запрет — строка ниже, и модуль
-- появляется у конкретного заклада.
--
-- Существующие заклады доводятся до того же набора: их всего один,
-- и он завёлся сегодня по этому же дефекту.

alter table public.tenants
  alter column modules set default array[
    'inventory'::public.tenant_module,
    'compliance'::public.tenant_module,
    'catalog'::public.tenant_module,
    'orders'::public.tenant_module,
    'customers'::public.tenant_module,
    'storefront'::public.tenant_module
  ];

-- Добираем недостающее, не отнимая уже подключённого: у заклада могли
-- быть модули, которых нет в умолчании, и терять их нельзя.
update public.tenants
   set modules = (
     select array_agg(distinct m order by m)
       from unnest(modules || array[
         'inventory'::public.tenant_module,
         'compliance'::public.tenant_module
       ]) as m
   )
 where not (modules @> array['inventory'::public.tenant_module,
                             'compliance'::public.tenant_module]);

comment on column public.tenants.modules is
  'Что заведение купило. Умолчание = продукт CRESKO: склад, соответствие, каталог, заказы, клиенты, витрина (0064).';
