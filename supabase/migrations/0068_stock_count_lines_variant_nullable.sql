-- 0068. Доделка 0066: строка пересчёта по расходнику не вставлялась.
--
-- КАК НАШЛОСЬ. Прогоном на чистом Postgres, тест 08_stock_plus:
--   ERROR: null value in column "variant_id" of relation "stock_count_lines"
--          violates not-null constraint
--
-- 0066 добавила material_id и ограничение «ровно одна из двух колонок»,
-- но у variant_id с самого начала стоял NOT NULL — он писался как
-- единственная цель пересчёта. Пока обе колонки не могут быть пустыми
-- по очереди, инвентаризация расходников остаётся невозможной, то есть
-- главный дефект 0066 был закрыт только на бумаге.
--
-- Целостность при этом не слабеет: stock_count_lines_one_target требует
-- ровно одну заполненную колонку из двух, и строка «ни товар, ни засіб»
-- по-прежнему не проходит.
--
-- Урок тот же, что и во всём проекте: «применилось» не значит «работает».
-- Поймал прогон исполнением, а не чтение диффа.

alter table public.stock_count_lines
  alter column variant_id drop not null;
