-- ===========================================================================
-- 0074. Четыре внешних ключа без индекса
--       + разбор находки по схеме net, которую МЫ ЗАКРЫТЬ НЕ МОЖЕМ
-- ===========================================================================
--
-- ── А. ЧЕТЫРЕ ВНЕШНИХ КЛЮЧА БЕЗ ИНДЕКСА ──────────────────────────────────
--
-- Внешний ключ без индекса по своей колонке означает, что удаление или
-- обновление РОДИТЕЛЬСКОЙ строки сканирует дочернюю таблицу целиком, и делает
-- это на каждую попытку. Пока строк мало — незаметно; станет заметно там,
-- где Postgres обязан проверить ссылку: при удалении профиля, сотрудника
-- или специальности. Удаление аккаунта (0058) как раз проходит по всему
-- графу ссылок, и каждый такой ключ — лишний полный проход.
--
-- Индексы частичные — `where … is not null`: во всех четырёх колонках пусто
-- в большинстве строк, полный индекс хранил бы пустоту.
--
-- ── Б. СХЕМА net ОТКРЫТА ролям anon и authenticated. И это НЕ ЧИНИТСЯ ─────
--
-- Найдено сплошной проверкой 15.08.2026. Двенадцать функций расширения
-- pg_net, включая `net.http_get`, `net.http_post`, `net.http_delete`,
-- `net.worker_restart`, стоят БЕЗ ACL — то есть право EXECUTE есть у PUBLIC,
-- а значит и у ролей `anon` и `authenticated`. USAGE на саму схему выдан
-- им же явно.
--
-- Чем это было бы, будь оно достижимо: право заставить базу сходить
-- по произвольному адресу с произвольными заголовками — SSRF из базы,
-- обращения во внутреннюю сеть, вынос данных через адрес запроса.
--
-- ПОЧЕМУ СЕЙЧАС НЕ ДОСТИЖИМО. PostgREST отдаёт наружу только схемы
-- из списка Exposed schemas (public, graphql_public). Схемы `net` там нет,
-- и вызвать её функции через API нельзя ни анониму, ни вошедшему.
-- То есть рубеж один — настройка, а не права.
--
-- ПОЧЕМУ ЗДЕСЬ НЕТ REVOKE. Первая редакция этой миграции его содержала.
-- Применилась без ошибки — и НЕ СРАБОТАЛА: проверка после применения
-- показала те же права. Причина в том, что схема `net` и все её функции
-- принадлежат роли `supabase_admin`, а миграции выполняются от `postgres`.
-- REVOKE, отданный не владельцем и без grant option, Postgres молча
-- пропускает. Роль `supabase_admin` платформой не выдаётся.
--
-- Оставлять «красивый» revoke, который ничего не делает, нельзя: следующий
-- читатель решит, что вопрос закрыт. Поэтому здесь его нет, а есть запись
-- о том, что вопрос ОТКРЫТ и закрывается не в базе.
--
-- ЕДИНСТВЕННАЯ ДЕЙСТВУЮЩАЯ ЗАЩИТА, И ЕЁ НАДО БЕРЕЧЬ:
--   Settings → API → Exposed schemas. Там должны остаться только
--   `public` и `graphql_public`. Добавление `net` в этот список открывает
--   SSRF немедленно и без единой правки кода. Тот, кто однажды его тронет,
--   об этом знать не будет — поэтому написано здесь.
-- ===========================================================================

create index if not exists invitations_invited_by_idx
  on public.invitations (invited_by) where invited_by is not null;

create index if not exists invitations_accepted_by_idx
  on public.invitations (accepted_by) where accepted_by is not null;

create index if not exists staff_blocked_by_idx
  on public.staff (blocked_by) where blocked_by is not null;

create index if not exists tenants_speciality_idx
  on public.tenants (speciality_id) where speciality_id is not null;
