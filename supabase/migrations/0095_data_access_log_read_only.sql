-- ===========================================================================
-- 0095. Журнал доступа к данным можно было ПОДДЕЛАТЬ. Догоняющая к 0090.
-- ===========================================================================
--
-- КАК НАШЛОСЬ. Прогоном `supabase/tests/run.sh` после того, как файлы
-- 0089–0094 наконец легли в репозиторий. Тест 09_team, п. «0082/Б:
-- представления никому не отдаются на запись», упал первым же запретом:
--   ПРОВАЛ: представлення відкриті на запис — data_access_log
--   (authenticated: DELETE, INSERT, TRUNCATE, UPDATE)
-- Проверено на бою: `has_table_privilege('authenticated',
-- 'public.data_access_log','INSERT')` = true. То есть это не особенность
-- стенда, а состояние продакшена.
--
-- ЧТО ПРОИСХОДИЛО. 0090 закончилась тремя строками:
--     revoke all on public.data_access_log from public;
--     revoke all on public.data_access_log from anon;
--     grant  select on public.data_access_log to authenticated;
-- Роль `authenticated` получает ALL на каждый новый объект схемы public
-- через `alter default privileges`, и `grant select` эту выдачу НЕ сужает —
-- он только добавляет право, которое уже есть. Отзыва у `authenticated`
-- не было, значит осталось всё: INSERT, UPDATE, DELETE, TRUNCATE.
--
-- ЭТО ЧЕТВЁРТЫЙ РАЗ. Те же грабли ловились в 0036 (тогда чинили только
-- anon), в 0061 (тогда выяснилось, что ролей две) и в 0094 (тогда — на
-- триггерных функциях). Вывод, записанный в 0094, оказался неполным:
-- он касался функций. Теперь он касается ЛЮБОГО объекта.
-- Правило: право отзывается тремя строками — public, anon И authenticated,
-- — и только потом выдаётся то единственное, которое нужно.
--
-- ЧЕМ ЭТО ГРОЗИЛО. `data_access_log` — обычное представление над
-- `audit_log`, то есть автоматически обновляемое. Оно НЕ security_invoker
-- (так задумано в 0090: оно само фильтрует по tenants_with), поэтому
-- запись через него идёт правами владельца и RLS таблицы `audit_log`
-- не применяется вовсе. Проверено исполнением на стенде под ролью
-- `authenticated`: `insert into public.data_access_log (...)` проходит,
-- строка появляется в `audit_log`.
--
-- Значит любой вошедший — в том числе мастер, которого завтра уволят, —
-- мог дописать в журнал доступа что угодно и от чьего угодно имени:
-- чужой actor_id, чужой tenant_id, любую подпись. `audit_log_guard`
-- этому не мешает: он роняет UPDATE и DELETE, а вставку разрешает —
-- её ведёт триггер `audit_row()`, и запрета на неё нет и быть не может.
--
-- Журнал, в который может писать кто угодно, доказательством не является.
-- Ровно это 0090 и обещала: «единственный способ понять источник утечки»
-- и «единственное доказательство обратного». До этой строки — не была.
--
-- ЧЕГО ЗДЕСЬ НЕТ. Файл 0090 не правится: он применён на бою, а расхождение
-- закрывается догоняющей миграцией. Форма идемпотентная: на бою она
-- отбирает лишнее, на пустой базе — просто выставляет верные права.
-- ===========================================================================

-- ── 1. Журнал доступа: только чтение ────────────────────────────────────────

revoke all on public.data_access_log from public;
revoke all on public.data_access_log from anon;
revoke all on public.data_access_log from authenticated;
grant select on public.data_access_log to authenticated;

-- ── 2. Гранты доступа сотрудников платформы: то же самое ────────────────────
--
-- Здесь дыры не было: на `platform_access_grants` включён RLS, а политика
-- ровно одна и она на SELECT — значит вставку и правку RLS отбивает даже
-- при выданном праве. Но 0093 прямым текстом говорит: «выдаёт и отзывает
-- только сервисный ключ; политик на insert и update нет, и это не упущение,
-- а решение». Право, противоречащее собственному решению миграции, — это
-- вторая линия обороны, снятая по невнимательности. Возвращаем.

revoke all on public.platform_access_grants from public;
revoke all on public.platform_access_grants from anon;
revoke all on public.platform_access_grants from authenticated;
grant select on public.platform_access_grants to authenticated;
