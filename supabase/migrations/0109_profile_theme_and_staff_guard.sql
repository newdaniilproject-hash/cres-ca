-- 0109. Тема как данные аккаунта + запрет самоповышения до сотрудника
--       платформы.
--
-- Здесь ДВА независимых изменения. Второе найдено при работе над первым
-- и названо отдельно, а не «заодно поправил»: они трогают одну таблицу,
-- но разные вещи.
--
-- ── 1. profiles.theme ───────────────────────────────────────────────────────
--
-- ЧТО ПОПРОСИЛ ВЛАДЕЛЕЦ (19.08.2026): «я хочу чтобы смена темы
-- синхронизировалась между вебом и мобом и запоминалась».
--
-- ПОЧЕМУ ЭТО НЕ ЧИНИТСЯ В КОДЕ. Тема лежала в `localStorage`, и это
-- работало ровно до второго устройства. Обёртка Capacitor открывает тот же
-- боевой сайт, НО в своём веб-вью — у него собственное хранилище, не общее
-- с Safari или Chrome того же телефона. То же и с кукой: у веб-вью своя
-- банка кук. Значит «одна тема на человека» невыразима на устройстве
-- в принципе — её знает только сервер.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ ТАБЛИЦА НАСТРОЕК. Настройка ровно одна и она
-- про человека, а не про заведение. Заводить `user_settings` под одно
-- поле значит завести join там, где хватает колонки; таблица появится
-- в тот день, когда настроек станет три, и это будет отдельное решение.
--
-- ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ — светлое: решение владельца 18.08.2026 сделало
-- светлую тему умолчанием продукта, и умолчание базы обязано совпадать
-- с умолчанием интерфейса. Иначе новый человек увидит тёмный кабинет,
-- которого не выбирал.
--
-- ЯЗЫК СЮДА НЕ ЕДЕТ. Колонка `profiles.locale` существует с 0001 и
-- не используется: язык живёт кукой, потому что его читает СЕРВЕР при
-- отрисовке кабинета, а тема нужна браузеру до первой отрисовки. Свести
-- их в одно место можно, но это отдельная работа с переносом чтения
-- языка на профиль — не побочный эффект этой миграции.

alter table public.profiles
  add column if not exists theme text not null default 'light'
    check (theme in ('light', 'dark'));

comment on column public.profiles.theme is
  'Выбранная человеком тема оформления. Одна на все его устройства: '
  'localStorage веб-вью обёртки и localStorage браузера — разные хранилища.';

-- ── 2. Сторож: `is_staff` нельзя поставить себе самому ──────────────────────
--
-- ЧТО НАЙДЕНО. Политика `profiles_self_update` (0001, переписана в 0093)
-- разрешает человеку менять СВОЮ строку целиком, без списка колонок:
--
--   using (id = auth.uid()) with check (id = auth.uid())
--
-- А в этой же строке лежит `is_staff` — «единственная глобальная привилегия
-- в системе» (её собственный комментарий в 0001). Хук выдачи токена читает
-- её и кладёт в `app_metadata.is_staff`, откуда её берут `is_platform_staff()`
-- и `has_platform_access()`. То есть любой вошедший мог выполнить
--
--   update public.profiles set is_staff = true where id = auth.uid();
--
-- перевойти — и получить признак сотрудника платформы. Отдельный грант
-- на заведение (0093) закрывает доступ к ЧУЖИМ данным заклада, но признак
-- открывает всё, что стоит на нём одном, и в первую очередь возможность
-- запрашивать такие гранты.
--
-- ПОЧЕМУ ТРИГГЕРОМ, А НЕ СУЖЕНИЕМ ПОЛИТИКИ. `with check` умеет проверить
-- новую строку, но не умеет сравнить её со старой: выражение вида
-- «is_staff не изменился» в политике не выразить. Колоночные гранты
-- (`grant update (col1, col2) on profiles`) выразили бы, но список колонок
-- в гранте устаревает молча — ровно та ошибка, что описана в CLAUDE.md
-- про ранний выход по списку колонок в 0080: новая колонка просто не
-- попадёт под правило, и никто этого не заметит. Триггер сравнивает
-- одно поле и не зависит от того, сколько их станет.
--
-- КОГО ПРОПУСКАЕМ. Всех, кроме ролей PostgREST: `postgres` (миграции,
-- ручная выдача признака), `service_role` (фоновые задачи). Проверка
-- по `current_user` — это роль, под которой исполняется запрос, и именно
-- её переключает PostgREST на `authenticated`/`anon` по токену.

create or replace function public.profiles_guard()
returns trigger language plpgsql set search_path to '' as $fn$
begin
  if new.is_staff is distinct from old.is_staff
     and current_user in ('authenticated', 'anon') then
    raise exception 'ознака співробітника платформи не змінюється з кабінету';
  end if;
  return new;
end $fn$;

drop trigger if exists profiles_guard on public.profiles;
create trigger profiles_guard
  before update on public.profiles
  for each row execute function public.profiles_guard();

-- Правило 7: Postgres выдаёт EXECUTE роли PUBLIC на каждую новую функцию.
-- Функция триггера вызывается самой базой и не нужна никому снаружи.
--
-- Отзывать надо ТРЕМЯ строками, а не одной. `from public` снимает право,
-- выданное самим Postgres, но в облаке Supabase поверх него работает
-- `alter default privileges ... grant all ... to anon, authenticated` —
-- и эти два гранта персональные, `from public` их не трогает. Ловится
-- это в проекте восьмой раз (0036, 0060, 0072, 0076, 0082 и далее);
-- здесь поймал тест `06_isolation.sql` на первом же прогоне, назвав
-- `profiles_guard` лишней функцией в списке открытых анониму.
revoke execute on function public.profiles_guard() from public;
revoke execute on function public.profiles_guard() from anon;
revoke execute on function public.profiles_guard() from authenticated;
grant  execute on function public.profiles_guard() to service_role;
