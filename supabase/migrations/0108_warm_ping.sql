-- ── Пинг, чтобы функция не засыпала ───────────────────────────────────────
--
-- ЗАЧЕМ. Замер 18.08.2026, страница входа `/m/login`, у которой нет ни одного
-- запроса к базе:
--
--   рендер локально, прогретый          16-29 мс
--   на бою, серверная часть             250-300 мс
--   на бою после простоя                800-930 мс
--
-- Первое число — это наш код. Второе — плата за то, что страницу рисует
-- функция в Дублине, и она уже близка к физике. А вот третье — подъём
-- заснувшего экземпляра, и оно к коду отношения не имеет вовсе.
--
-- На тарифе Hobby экземпляр засыпает быстро, а при двух-трёх пользователях
-- он спит почти всегда. То есть «холодный старт» здесь не редкая неудача,
-- а обычное состояние: владелец открывает приложение и каждый раз ждёт
-- лишнюю секунду.
--
-- ЧТО ДЕЛАЕМ. Раз в 5 минут дёргаем боевой адрес, чтобы экземпляр не успел
-- заснуть. Расписание уже крутится здесь же — `notifications-dispatch`
-- с тем же интервалом (0032), так что ни новой машинерии, ни нового
-- секрета не появляется.
--
-- ЧЕСТНО О ГРАНИЦАХ. Это ОБХОД, а не починка: мы прячем свойство тарифа.
-- Он снимает только третью строку замера; 250-300 мс тёплого времени
-- остаются, и убрать их можно лишь одним способом — не звать функцию там,
-- где страница не нуждается в данных (отдавать её с CDN). Это переделка
-- локализации, потому что язык сейчас читается из куки, а страницу,
-- зависящую от куки, закешировать нельзя.
--
-- Греется ОДИН экземпляр, а не все: Next раскладывает маршруты по
-- нескольким функциям. Поэтому адресов два — вход приложения и главная,
-- то есть то, с чего начинается сеанс.
--
-- ЦЕНА. 2 запроса × 12 раз в час × 24 = 576 в сутки, ~17 тыс. в месяц.
-- У Hobby лимит вызовов измеряется миллионами — это доли процента.
-- Ответ не читаем и ошибку не разбираем намеренно: цель не «проверить,
-- что сайт жив» (для этого есть сторож в GitHub Actions), а просто
-- разбудить. Пинг, который умеет падать с ошибкой, — это ещё одно
-- место, которое надо чинить.
--
-- Заголовка авторизации здесь нет и быть не должно: оба адреса
-- публичные, `/m/login` — форма входа, `/` — витрина.

select cron.unschedule('warm-ping')
 where exists (select 1 from cron.job where jobname = 'warm-ping');

select cron.schedule(
  'warm-ping',
  '*/5 * * * *',
  $$
  -- www, а не апекс: апекс отдаёт 308 на www, и разбудить редиректом
  -- нельзя — функция при этом не вызывается вовсе.
  select net.http_get(url := 'https://www.cres-ca.com/m/login',
                      timeout_milliseconds := 10000);
  select net.http_get(url := 'https://www.cres-ca.com/',
                      timeout_milliseconds := 10000);
  $$
);
