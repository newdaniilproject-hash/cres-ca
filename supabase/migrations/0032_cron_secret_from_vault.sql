-- плюс переменная на хостинге, без миграции и без правки расписания.
-- И `select command from cron.job` больше не показывает секрет.

-- Снимаем старое задание по имени. unschedule по имени, а не по jobid:
-- jobid на разных базах разный, а имя одно и то же.
select cron.unschedule('notifications-dispatch')
 where exists (select 1 from cron.job where jobname = 'notifications-dispatch');

select cron.schedule(
  'notifications-dispatch',
  '*/5 * * * *',
  $$
  select net.http_get(
    url := 'https://cres-ca.com/api/cron/notifications',
    headers := jsonb_build_object(
      'Authorization',
      'Bearer ' || (select decrypted_secret
                      from vault.decrypted_secrets
                     where name = 'cron_secret'
                     limit 1)),
    timeout_milliseconds := 55000
  );
  $$
);

