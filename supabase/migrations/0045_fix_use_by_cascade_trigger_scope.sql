-- 0045. Исправление собственной ошибки в 0044: каскад срока по дереву
-- ёмкостей не срабатывал.
--
-- ЧТО БЫЛО. В 0044 каскад повешен как
--   create trigger ... after update OF use_by on material_containers
-- Расчёт был на то, что триггер сработает всякий раз, когда столбец
-- use_by фактически изменился.
--
-- ПОЧЕМУ ЭТО ДЕФЕКТ. В PostgreSQL «UPDATE OF col» срабатывает, если
-- столбец ПЕРЕЧИСЛЕН в SET исходного запроса, а не если его значение
-- изменилось. use_by в SET никто не пишет — его вычисляет BEFORE-триггер
-- containers_guard. Поэтому каскад не запускался никогда.
--
-- ЧЕМ ГРОЗИЛО. Половина правила 0044 не работала: срок дочерней ёмкости
-- зажимался только в момент её создания. Если срок родителя укорачивали
-- задним числом (перепривязали партию), дети оставались с прежней, более
-- длинной датой — то есть ровно та подделка срока, которую 0044 закрывала,
-- возвращалась через боковую дверь. Замер до этой миграции: родитель
-- 2026-08-27 -> 2026-08-20, дочь и внучка остались 2026-08-27.
--
-- ЧТО СТАЛО. Триггер переведён на обычный AFTER UPDATE с условием
-- WHEN (new.use_by is distinct from old.use_by). WHEN вычисляется уже
-- после BEFORE-триггеров, поэтому видит настоящее новое значение.
-- Это же условие страхует от бесконечной рекурсии: как только пересчёт
-- перестаёт менять срок, каскад глохнет сам.
-- Проверено: родитель 2026-08-27 -> 2026-08-20 тянет за собой дочь и
-- внучку в 2026-08-20; UPDATE, не меняющий срок, каскад не запускает.

drop trigger if exists material_containers_use_by_cascade on public.material_containers;

create trigger material_containers_use_by_cascade
after update on public.material_containers
for each row
when (new.use_by is distinct from old.use_by)
execute function public.containers_propagate_use_by();
