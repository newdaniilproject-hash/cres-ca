-- ===========================================================================
-- 0086. Сторож журнала безопасности получает `search_path = ''`.
--       Однострочная починка 0085, найденная анализатором сразу после накатa.
-- ===========================================================================
--
-- ЧТО БЫЛО. `security_events_immutable()` из 0085 — единственная функция
-- во всём проекте без заданного `search_path`. Проверено на бою: у всех
-- её братьев — `audit_log_guard`, `journal_guard`, `tech_cards_guard`,
-- `permission_audit_immutable` — стоит `search_path=""`, у неё не стояло.
-- Анализатор Supabase (lint 0011, function_search_path_mutable) выдал
-- ровно одно замечание на всю базу, и это была она.
--
-- ЧЕМ ЭТО ОПАСНО ИМЕННО ЗДЕСЬ. Функция не SECURITY DEFINER, поэтому прямой
-- дыры нет: подставленная в чужой схеме `coalesce` исполнилась бы правами
-- того же вызывающего. Но это сторож НЕИЗМЕНЯЕМОГО журнала, и его решение
-- «пропустить или уронить» зависит от `current_setting('app.purging_account')`.
-- Функция, чьё решение зависит от разбора имён по пути, который задаёт
-- вызывающий, — не то, на чём должен стоять запрет переписывать журнал
-- безопасности. Плюс правило простое: у сторожей журналов путь задан
-- у всех четверых, и исключение из четырёх — это не исключение, а пропуск.
--
-- ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ПРАВКА 0085. 0085 уже применена на бою:
-- журнал применённого — это запись факта, а не список пожеланий (тот же
-- довод, что в NAME-ALIASES.txt). Правка задним числом развела бы текст
-- в репозитории с тем, что реально накатывалось. Так же чинились 0023
-- (в 0028) и 0076 (в 0080).
--
-- Тело переносится из 0085 ДОСЛОВНО: меняется только строка конфигурации.
-- `coalesce`, `current_setting` и `tg_op` живут в pg_catalog, который
-- подставляется всегда, — под пустым путём они работают как работали.
-- ===========================================================================

create or replace function public.security_events_immutable()
returns trigger language plpgsql set search_path = '' as $fn$
begin
  -- Единственная законная щель — удаление аккаунта (0058). Флаг живёт
  -- только внутри своей транзакции, снаружи запрет действует как действовал.
  if coalesce(current_setting('app.purging_account', true), 'off') = 'on'
     and tg_op = 'DELETE' then
    return old;
  end if;
  raise exception 'журнал безпеки незмінний: % заборонено', tg_op;
end $fn$;

revoke all on function public.security_events_immutable() from public, anon, authenticated;
