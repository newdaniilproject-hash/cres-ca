// ⚠️ ВТОРОГО СЛОВАРЯ НЕТ И НЕ БУДЕТ. Здесь только вызов `createT` из
// `lib/i18n/translate.ts` — того самого переводчика, которым живёт веб.
// В его шапке написано «Ни React, ни Next: одна и та же функция работает
// в серверном компоненте и в клиентском»; телефон — третий такой случай,
// и ничего дописывать ради него не пришлось.
//
// Что это даёт практически: 2720 ключей `uk.json` доступны мобильному
// приложению в день, когда их правят для веба. Захардкоженная строка
// «на минутку» остаётся навсегда — правило проекта, и на телефоне оно
// то же самое.
//
// Выбор языка человеком здесь пока не читается: в вебе он живёт в куке,
// на телефоне ему нужен свой склад (профиль в базе — как у темы, 0109).
// До тех пор украинский по умолчанию — ровно то, что видит большинство.

import type { Key } from '../../lib/i18n/dict'
import { createT } from '../../lib/i18n/translate'

export const t = createT('uk')

/**
 * Подпись права по его ключу. Право БЕЗ подписи печатается своим ключом,
 * а не прячется — тот же приём, что в вебе (бриф П1, 25.08.2026):
 * новое право видно в день миграции, а не после правки словаря.
 *
 * Отдельной функцией, потому что ключ здесь собирается из строки
 * (`perm.stock.read`), а `t()` принимает только известные ключи —
 * на том и держится проверка опечаток во всём остальном коде.
 */
export function permLabel(perm: string): string {
  const key = `perm.${perm}` as Key
  const text = t(key)
  return text === key ? perm : text
}
