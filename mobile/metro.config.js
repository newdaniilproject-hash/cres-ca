// Сборщик мобильного приложения.
//
// ЗАЧЕМ ФАЙЛ ВООБЩЕ. Metro по умолчанию видит только то, что лежит внутри
// своей папки. Общий слой (`../shared`) и чистые модули веба (`../lib`)
// лежат ВЫШЕ, и без списка ниже сборка падает на первом же импорте
// «модуль не найден» — при том что файл существует и редактор его видит.
//
// ⚠️ ПРАВИЛО, КОТОРОЕ НЕЛЬЗЯ НАРУШАТЬ: из `../lib` мобильному можно брать
// ТОЛЬКО чистые модули — те, что не импортируют ничего, кроме соседних
// файлов и JSON. Сегодня это `lib/i18n/*` (в шапке `translate.ts` прямо
// написано «ни React, ни Next»), `lib/expiry.ts`, `lib/design/tokens.ts`.
//
// Почему нельзя брать остальное. На машине разработчика рядом с этим
// файлом стоит ВТОРОЙ node_modules — корневой, для Next. В нём свои
// `react` и `react-dom`, и версии у них другие. Файл из `../lib`,
// который импортирует пакет, Metro будет искать сначала в корневом
// node_modules — то есть в бандл телефона приедет вторая копия React.
// Симптом: белый экран и «Invalid hook call» без внятного стека,
// причём только на машине, где веб уже собирали хоть раз.
//
// Поэтому граница проведена не «по папкам», а по СВОЙСТВУ: общий модуль
// не имеет зависимостей времени выполнения. Клиент Supabase в общий слой
// не импортируется, а передаётся параметром — см. `shared/inventory.ts`.

const { getDefaultConfig } = require('expo/metro-config')
const path = require('node:path')

const projectRoot = __dirname
const repoRoot = path.resolve(projectRoot, '..')

const config = getDefaultConfig(projectRoot)

// Что Metro читает и отслеживает помимо своей папки.
config.watchFolders = [
  path.join(repoRoot, 'shared'),
  path.join(repoRoot, 'lib'),
]

// Пакеты берём только свои. Корневой node_modules веба сюда не приглашён
// (см. предупреждение выше); список задан явно, чтобы это было решением,
// а не следствием того, что корневой каталог сегодня пуст.
config.resolver.nodeModulesPaths = [path.join(projectRoot, 'node_modules')]

module.exports = config
