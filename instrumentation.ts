// Проверка переменных окружения ПРИ СТАРТЕ, а не в середине обработчика.
//
// ЗАЧЕМ. Забытая переменная не подаёт признаков: приложение поднимается,
// страницы открываются, и всё выглядит рабочим — пока кто-нибудь не дёрнет
// конкретный роут. 14.08.2026 это стоило двух находок подряд:
//   * CRON_SECRET не совпадал — крон отдавал 401 каждые 5 минут одиннадцать
//     часов подряд, и это никого не разбудило;
//   * SUPABASE_SERVICE_ROLE_KEY не задан — выяснилось только после того, как
//     починили первое: один отказ ПРЯТАЛ другой, потому что обработчик
//     отбивал на авторизации и до подключения к базе не доходил.
// При сегодняшнем нуле трафика «выяснится, когда дёрнут роут» означает
// «через месяц». Отчёт при старте виден в логах деплоя сразу.
//
// ПОЧЕМУ НЕ БРОСАЕТ ИСКЛЮЧЕНИЕ. Соблазн «нет переменной — падаем» здесь
// вреден: незаданный ключ пушей уронил бы витрину, склад и журналы, то есть
// превратил бы частичный отказ в полный. Поэтому громко в лог — и ни одного
// падения. Канал, который не настроен, честно бросает в момент отправки
// (lib/notify/send.ts) и попытка откладывается очередью — это правильное
// место для отказа канала.
//
// ЗНАЧЕНИЯ В ЛОГ НЕ ПОПАДАЮТ НИКОГДА. Печатаются только имена.

type Check = {
  name: string
  /** Что перестаёт работать, если её нет. Пишется для человека в логе. */
  breaks: string
}

// Без этих двух не работает разбор очереди уведомлений — единственная
// фоновая задача проекта.
const REQUIRED: Check[] = [
  { name: 'SUPABASE_SERVICE_ROLE_KEY', breaks: 'разбор очереди уведомлений: нет подключения к базе' },
  { name: 'CRON_SECRET', breaks: 'разбор очереди уведомлений: роут отбивает вызов крона как чужой' },
]

// Каналы. Их отсутствие гасит ОДИН способ доставки, а не приложение.
const CHANNELS: Check[] = [
  { name: 'RESEND_API_KEY', breaks: 'письма: код при регистрации, заказы, напоминания, сроки годности' },
  { name: 'ONESIGNAL_APP_ID', breaks: 'пуши (серверная половина)' },
  { name: 'ONESIGNAL_API_KEY', breaks: 'пуши (серверная половина)' },
  { name: 'NEXT_PUBLIC_ONESIGNAL_APP_ID', breaks: 'пуши в приложении: клиент не инициализируется' },
]

// Необязательные: у каждой есть осмысленное умолчание, и отсутствие —
// это выбор, а не поломка. Печатаются отдельной строкой, чтобы не путать
// с настоящей нехваткой.
const OPTIONAL: Check[] = [
  { name: 'RESEND_FROM_EMAIL', breaks: 'адрес отправителя берётся по умолчанию' },
  { name: 'ANDROID_CERT_SHA256', breaks: 'App Links не подтверждаются: ссылки откроются в браузере' },
  { name: 'ANDROID_CERT_SHA256_DEBUG', breaks: 'то же для отладочной сборки' },
  // Эти две имеют ЗАХАРДКОЖЕННЫЙ фолбэк в lib/supabase/config.ts.
  // Значит их отсутствие ничего не ломает, но и не заметно — а при переезде
  // на другой проект Supabase молча оставит прод на старом. Поэтому здесь.
  { name: 'NEXT_PUBLIC_SUPABASE_URL', breaks: 'берётся зашитый в код адрес проекта' },
  { name: 'NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY', breaks: 'берётся зашитый в код публикуемый ключ' },
]

const missing = (list: Check[]) => list.filter((c) => !process.env[c.name])

export function register() {
  // Только серверная среда Node. В edge и в браузере проверять нечего.
  if (process.env.NEXT_RUNTIME !== 'nodejs') return

  const lines: string[] = []
  const req = missing(REQUIRED)
  const ch = missing(CHANNELS)
  const opt = missing(OPTIONAL)

  if (req.length > 0) {
    lines.push('НЕ ЗАДАНЫ ОБЯЗАТЕЛЬНЫЕ:')
    for (const c of req) lines.push(`  ${c.name} — ${c.breaks}`)
  }
  if (ch.length > 0) {
    lines.push('НЕ НАСТРОЕНЫ КАНАЛЫ ДОСТАВКИ:')
    for (const c of ch) lines.push(`  ${c.name} — ${c.breaks}`)
  }
  if (opt.length > 0) {
    lines.push('Не заданы необязательные (работает умолчание):')
    for (const c of opt) lines.push(`  ${c.name} — ${c.breaks}`)
  }

  if (lines.length === 0) {
    console.log('[env] все известные переменные окружения на месте')
    return
  }

  // Одним блоком, а не построчно: в логе Vercel строки перемешиваются
  // с чужими, и разорванный отчёт читать невозможно.
  console.warn(
    ['[env] проверка переменных окружения при старте', ...lines,
      'Значения не печатаются — только имена. Список и назначение: CLAUDE.md,',
      'раздел «Что настраивается руками».'].join('\n'),
  )
}
