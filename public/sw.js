/* Service worker. У него РОВНО ОДНА задача: показать экран «немає мережі»
   вместо пустой страницы, когда связи нет. Всё остальное он делать перестал,
   и ниже написано почему — чтобы это не «оптимизировали» обратно.

   Три правила, нарушение любого ломает вход:

   1. Запросы к Supabase НЕ трогаем вообще. Там сидит авторизация,
      и отданный из кеша ответ означал бы чужую сессию или устаревшие
      остатки, показанные как свежие.
   2. POST и всё, что меняет данные, не кешируем никогда.
   3. Страницы и файлы сборки из кеша НЕ отдаём. Никогда.

   ── Разбор отказа 18.08.2026: «тяну обновить — возвращается старый стиль» ──

   Владелец выкатил новое оформление, открыл приложение, потянул страницу
   вниз — и получил обратно предыдущий вид. Выглядело как незакончившийся
   выкат, а причина была здесь, и она из двух половин, каждая безобидная
   по отдельности:

   A. ФАЙЛЫ `/_next/static/` ОТДАВАЛИСЬ ИЗ КЕША ПЕРВЫМИ и складывались
      в кеш `shell-<VERSION>`, который чистится ТОЛЬКО при смене VERSION
      руками. То есть стили каждой прошлой сборки оставались на телефоне
      навсегда.
   Б. СТРАНИЦЫ КЛАЛИСЬ В КЕШ и отдавались из него, как только сеть
      подвела хоть на мгновение — а «потянул обновить» на телефоне это
      ровно тот момент, когда соединение ещё не поднялось.

      Вместе: из кеша приезжал ВЧЕРАШНИЙ HTML, он просил вчерашний
      css с прежним хешем — а тот лежал рядом, живой и вечный. Страница
      собиралась целиком в прошлом виде и выглядела абсолютно исправной.
      Ни одной ошибки в консоли: обе половины отработали как написано.

   ПОЧЕМУ ЛЕЧИМ УДАЛЕНИЕМ, А НЕ ВЕРСИЕЙ. Соблазн — «просто поднять
   VERSION при каждом выкате». Это ручное действие, привязанное к чужому
   событию: забыть его нельзя заметить, и заметит его владелец через
   неделю на телефоне, как сейчас. Ровно тем же способом уже накопился
   отказ 15.08.2026 (пункт В прежней шапки: «VERSION не менялся никогда»).
   Второй раз чинить дисциплиной то, что чинится удалением кода, — ошибка.

   А кешировать тут и нечего: файлы сборки Vercel отдаёт с
   `immutable, max-age=31536000`, то есть обычный HTTP-кеш браузера делает
   ту же работу и сам выбрасывает лишнее. Страницы же приходят с сервера
   и офлайн-чтения в вебе не дают в принципе (CLAUDE.md, «Офлайн-режим»):
   кеш страниц не приближал офлайн ни на шаг, он только показывал вчерашнее
   как сегодняшнее.

   ── Разбор отказа 15.08.2026: «выключил интернет — чёрный экран» ──

   Запасным экраном была СТРАНИЦА Next `/offline`, а её HTML ссылается на
   `/_next/static/...` с хешем сборки в имени. Через сборку хеши сменились,
   офлайн отдавали старый HTML, он просил файлы, которых уже нет, — браузер
   рисовал ровно ничего.

   Теперь запасной экран — `/offline.html`: один файл, стили и скрипт
   внутри, ни одной внешней ссылки. Он не может «протухнуть», потому что
   ему не на что ссылаться. Тот же файл служит запасным экраном и нативной
   оболочке — второй копии не заводим.

   И `cache.addAll` не используем: один недоступный адрес отклоняет весь
   Promise, установка падает, service worker не активируется ВОВСЕ — молча,
   потому что ошибка установки в интерфейсе не видна.
*/

const VERSION = 'v3'
const SHELL = `shell-${VERSION}`

// Запасной экран — первым и отдельной строкой: без него офлайн не имеет
// смысла, а всё остальное в списке — необязательная приятность.
const OFFLINE_URL = '/offline.html'
const PRECACHE = [OFFLINE_URL, '/manifest.webmanifest', '/icon-192.png', '/icon-512.png']

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL)

    // Поимённо и по одному — см. про `addAll` в шапке.
    await Promise.allSettled(PRECACHE.map((url) => cache.add(url)))

    // Запасной экран проверяем отдельно: если не лёг именно он, офлайна
    // нет вовсе, и это стоит увидеть в консоли, а не гадать.
    if (!(await cache.match(OFFLINE_URL))) {
      console.error(`[sw] ${OFFLINE_URL} не потрапив у кеш — офлайн-екран не покажеться`)
    }

    await self.skipWaiting()
  })())
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // Сносим ВСЁ, что не наш текущий SHELL. Здесь же уезжают кеши
    // `shell-v2` и `pages-v2` со стилями и страницами прошлых сборок —
    // тот самый «старый стиль», который возвращался при обновлении.
    const keys = await caches.keys()
    await Promise.all(keys.filter((k) => k !== SHELL).map((k) => caches.delete(k)))
    await self.clients.claim()
  })())
})

// Позволяет странице попросить обновиться немедленно.
self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting()
})

self.addEventListener('fetch', (event) => {
  const req = event.request

  // Перехватываем ТОЛЬКО переходы по страницам. Всё остальное — файлы
  // сборки, картинки, запросы к Supabase — идёт мимо нас к браузеру,
  // и это не упущение, а решение: см. шапку.
  if (req.method !== 'GET' || req.mode !== 'navigate') return

  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return

  event.respondWith((async () => {
    try {
      // Ответ НЕ кладётся в кеш. Совсем. Единственный смысл этого
      // обработчика — подменить ошибку сети экраном, а не подсунуть
      // вчерашнюю страницу вместо сегодняшней.
      return await fetch(req)
    } catch {
      // Запасной экран ищем без учёта строки запроса: иначе
      // `/offline.html?x=1` не найдёт `/offline.html`.
      const fallback = await caches.match(OFFLINE_URL, { ignoreSearch: true })
      if (fallback) return fallback

      // Досюда доходим, только если не легло вообще ничего. Текстом,
      // потому что любая разметка здесь снова зависела бы от файлов.
      return new Response(
        'Немає мережі. Перевірте звʼязок і спробуйте ще раз.',
        { status: 503, headers: { 'Content-Type': 'text/plain; charset=utf-8' } },
      )
    }
  })())
})
