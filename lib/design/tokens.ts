// ── Один источник правды для СТИЛЯ вне таблицы стилей ───────────────────────
//
// Требование владельца 19.08.2026: «если стили, то оно в одном месте. Если
// я изменил, то оно меняет всё. И чтобы не остались где-то артефакты старые».
//
// ЧТО БЫЛО. Палитр в продукте было ЧЕТЫРЕ, и три из них никто не менял
// при смене оформления:
//
//   • `app/globals.css`               — текущая (CRESKO);
//   • `lib/report/sanitation-report.ts` — сепия ПЕРВОГО оформления
//     (#16150f, #22443a, #6a6355, #ddd7cb). Это отчёт для проверки —
//     то есть документ, который клиент несёт в Держпродспоживслужбу;
//   • `lib/report/labels.ts`          — своя, у наклеек на банках;
//   • `lib/email/*`                   — своя, у писем клиенту.
//
// Плюс мелочи: экран отказа при превышении лимита, счётчик колокола,
// заставка обёртки. Сменить тему и не тронуть их — значит получить
// продукт, который в интерфейсе выглядит одним, а на бумаге и в почте
// другим. Это и есть «старые артефакты».
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО ВЗЯТЬ ПЕРЕМЕННЫЕ CSS. Три потребителя вне браузера:
//
//   1. PDF-отчёт и наклейки собираются СТРОКОЙ HTML на сервере и печатаются.
//      В печати `var(--…)` работает, но тема к бумаге отношения не имеет:
//      документ обязан быть светлым и контрастным независимо от того, какую
//      тему выбрал человек. Значения нужны буквальные.
//   2. Письма верстаются инлайновым стилем: почтовые клиенты вырезают
//      `<style>` из `<head>` и переменных не понимают вовсе.
//   3. Нативная оболочка (`capacitor.config.ts`, статус-бар) получает цвет
//      строкой в конфигурации сборки, до всякого CSS.
//
// ПОЭТОМУ значения живут ЗДЕСЬ, а `globals.css` держит те же числа в виде
// переменных. Две записи одной таблицы неизбежны — и именно поэтому рядом
// стоит СТОРОЖ: `scripts/check-tokens.mjs` читает `globals.css`, сверяет
// с этим файлом и роняет сборку при расхождении. Без сторожа «один
// источник правды» — это обещание, а не свойство.

