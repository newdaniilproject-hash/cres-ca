import type { SupabaseClient } from '@supabase/supabase-js'

// ===========================================================================
// ЖУРНАЛ ПОДОЗРИТЕЛЬНЫХ СОБЫТИЙ — сторона приложения.
// ===========================================================================
//
// База даёт одну точку — `log_security_event(вид, арендатор, подробности)`
// (0085). Почему её зовёт ПРИЛОЖЕНИЕ, а не триггер, разобрано в шапке той
// же миграции, и пересказывать это здесь не нужно; помнить надо два вывода,
// потому что из них следует ВСЁ устройство этого файла:
//
//  1. ОТКАТ. И `with check` на чужом `tenant_id`, и сторож неизменяемой
//     записи роняют транзакцию ЦЕЛИКОМ. Запись в журнал, сделанная внутри
//     той же транзакции, откатится вместе с попыткой — строка о событии
//     исчезнет ровно вместе с событием. Поэтому звать функцию можно только
//     из кода, ПОЙМАВШЕГО ошибку, то есть уже снаружи откаченной транзакции.
//     Отсюда форма вызова: не «перед», не «вместо», а в `catch` / в ветке
//     `if (error)`.
//  2. ФУНКЦИЯ НЕ ВЕРИТ ВЫЗЫВАЮЩЕМУ. Автор берётся из `auth.uid()`, вид —
//     из закрытого списка, «обращение к чужому» принимается только если
//     арендатор действительно не свой, а «правка неизменяемого» — только
//     если свой. Сочинить событие, которого не могло быть, нельзя. Значит
//     и проверять здесь нечего: неверный вызов честно откажет.
//
// ⚠️ `false` В ОТВЕТЕ — НЕ ОШИБКА. Функция держит собственный ограничитель:
// одна строка в минуту на пару «вид × автор × арендатор», иначе журнал
// владельца топится в спаме за один цикл. Сработал ограничитель — вернётся
// `false`, и реагировать на это не надо ничем. Ровно поэтому все функции
// ниже возвращают `void`: показывать разницу наружу значило бы предложить
// на неё реагировать.
//
// ⚠️ И ГЛАВНОЕ: НИ ОДНА ОШИБКА ЗАПИСИ В ЖУРНАЛ НЕ ВЫХОДИТ НАРУЖУ. Человек
// в этот момент уже получил отказ по делу; заменить его на «не вдалося
// записати подію журналу» — это подменить причину. Сторож, о котором никто
// не узнал, хуже сторожа, которого нет, поэтому неудача уходит в консоль
// предупреждением — как в `auth_session_device_watch()` в самой базе.

type Kind = 'tenant.foreign_access' | 'record.immutable_attempt'

/** Подробности: две известные строки, база обрежет каждую до 200 знаков. */
export type SecurityDetail = { what?: string; where?: string }

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

async function write(
  supabase: SupabaseClient, kind: Kind, tenantId: string, detail: SecurityDetail,
): Promise<void> {
  // Не uuid — в базу не идём вовсе: это не событие, а мусор в параметре,
  // и `22P02` в журнале сервера только уводит в сторону.
  if (!UUID.test(tenantId)) return
  try {
    const { error } = await supabase.rpc('log_security_event', {
      p_kind: kind,
      p_tenant_id: tenantId,
      p_detail: { what: detail.what ?? '', where: detail.where ?? '' },
    })
    if (error) throw new Error(error.message)
  } catch (e) {
    console.warn('[security] подію не записано:',
      e instanceof Error ? e.message : String(e))
  }
}

/**
 * Обращение к ЯВНО НАЗВАННОМУ чужому арендатору: адрес, параметр запроса,
 * тело, `p_tenant_id` у RPC — и членства в нём нет.
 *
 * Чего сюда класть НЕЛЬЗЯ, и это не придирка: обычное ЧТЕНИЕ, вернувшее
 * ноль строк. Для базы «покажи заказы заклада X» от чужого и тот же запрос
 * от своего, у которого заказов пока нет, НЕРАЗЛИЧИМЫ — оба успешны, оба
 * пусты. Записать первое «по подозрительности» значит гадать, а гадание
 * в журнале безопасности хуже пустоты: по нему потом принимают решение
 * об увольнении.
 */
export async function logForeignTenant(
  supabase: SupabaseClient, tenantId: string, detail: SecurityDetail,
): Promise<void> {
  await write(supabase, 'tenant.foreign_access', tenantId, detail)
}

/**
 * Пойманная ошибка сторожа неизменяемой записи. Арендатор — СВОЙ: правка
 * в чужом закладе невозможна физически, и такое событие база не примет.
 */
export async function logImmutableAttempt(
  supabase: SupabaseClient, tenantId: string, detail: SecurityDetail,
): Promise<void> {
  await write(supabase, 'record.immutable_attempt', tenantId, detail)
}

// ── Узнавание сторожа по тексту отказа ─────────────────────────────────────
//
// Отдельной функцией, а не строкой в каждом экране: сторожей девять, и
// список, размазанный по девяти файлам, устаревает в тот день, когда
// заводят десятого.
//
// ⚠️ Подстроки — это ТЕКСТ ОТКАЗА ИЗ МИГРАЦИЙ, а не ключи словаря. Их не
// переводят никогда: переведи — и разбор перестанет узнавать свой же случай
// (та же оговорка стоит в `lib/auth-errors.ts` и в `teamErrorText`). Часть
// написана по-русски, часть по-украински — ровно так, как они лежат
// в миграциях, а не так, как хотелось бы.
//
// Ловим по КОРОТКОМУ куску без подставляемых значений: «накладна % проведена»
// приезжает с номером документа внутри, «рух складу %» — с идентификатором.
const GUARDS = [
  'запись санитарного журнала неизменяема',   // 0014, дезрастворы/уборка/стерилизация
  'дата вскрытия не редактируется',           // 0014, ёмкость
  'утверждённая версия техкарты неизменна',   // 0014, техкарта
  'техкарта не удаляется',                    // 0014, техкарта
  'финансовая запись не удаляется',           // 0007, финансы
  'не правятся — только заметка',             // 0007, финансы
  'не можна змінити або видалити',            // 0066, движение склада
  'проведена: змінити або видалити її не можна', // 0066/0069, накладная
  'журнал дій не редагується і не видаляється',  // 0021, журнал действий
  'журнал прав незмінний',                    // 0076/0081, журнал прав
  'журнал безпеки незмінний',                 // 0085/0086, этот самый журнал
]

/** Похож ли отказ на сторожа неизменяемой записи. */
export function isImmutableGuard(message: string): boolean {
  const m = message.toLowerCase()
  return GUARDS.some((g) => m.includes(g))
}

/**
 * Свой заклад, когда экран его под рукой не держит.
 *
 * Запрос к базе, и это осознанно: он делается ТОЛЬКО на пути отказа, уже
 * после того, как сторож уронил операцию, — то есть раз в жизни экрана,
 * а не на каждом рендере. Правило 3 («роль берётся из JWT, не из базы»)
 * не нарушено: здесь читается не право, а идентификатор заклада, и читается
 * он политикой того же вошедшего.
 *
 * Разбирать токен руками, как `lib/tenant.ts`, тут нельзя: тот файл
 * серверный (тянет `next/headers`), а сторожа ловят клиентские экраны.
 * Вторая копия разбора JWT — ровно то, что запрещает «Общий слой вместо
 * паритета»: две копии всегда разъезжаются.
 */
async function myTenantId(supabase: SupabaseClient): Promise<string | null> {
  const { data, error } = await supabase
    .from('tenant_members').select('tenant_id').limit(1)
  if (error || !data || data.length === 0) return null
  const id = (data[0] as { tenant_id?: unknown }).tenant_id
  return typeof id === 'string' ? id : null
}

/**
 * Удобная связка для экрана: «поймал отказ — если это сторож, запиши».
 *
 * Возвращает `void` намеренно (см. шапку): экран показывает свой текст
 * отказа независимо от того, попала строка в журнал или нет. Вызов
 * не ждут — `void noteIfImmutable(...)` рядом с `setErr(...)`, потому что
 * человеку в этот момент нужен ответ, а не наша бухгалтерия.
 *
 * `tenantId` необязателен: экраны, которые его и так держат, передают
 * его и экономят запрос; остальные не плодят ради этого лишний проп.
 */
export async function noteIfImmutable(
  supabase: SupabaseClient, message: string, where: string, tenantId?: string,
): Promise<void> {
  if (!isImmutableGuard(message)) return
  const tenant = tenantId ?? await myTenantId(supabase)
  if (!tenant) return
  await logImmutableAttempt(supabase, tenant, { what: message, where })
}
