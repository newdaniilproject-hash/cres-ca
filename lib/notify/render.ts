// Подстановка {{плейсхолдеров}} в шаблон. Шаблоны живут в базе
// (notification_templates), не в коде — см. комментарий в 0011_notifications.sql:
// «событие описывается один раз».

// ── ДАТА В ПИСЬМЕ ЧИТАЕТСЯ ПО-УКРАИНСКИ, А НЕ ПО-МАШИННОМУ ──────────────────
//
// Найдено 25.08.2026, когда Resend и OneSignal заработали и письма пошли
// на живой телефон. Предупреждение о сроке годности выглядело так:
//
//   «Спрей-антизаплутування (CR-0001): термін придатності спливає
//    2026-09-08 — за 14 днів»
//
// Дата попадает в payload прямо из колонки `use_by` (0014, 0022:
// `jsonb_build_object(..., 'use_by', new.use_by)`), а `jsonb` печатает
// дату в ISO. Формально верно, читается как строка из журнала сервера —
// и это ровно то место, где мастер должен за секунду понять, сколько
// у него осталось.
//
// ПОЧЕМУ ЧИНИТСЯ ЗДЕСЬ, А НЕ В БАЗЕ. Соблазн — обернуть колонку
// в `to_char` в самих триггерах. Но enqueue-вызовов со сроком уже два
// (0014 для ёмкости, 0022 для партии), и каждый следующий шаблон
// с датой пришлось бы помнить оборачивать. Здесь же правило одно
// на все шаблоны, включая те, что арендатор перепишет сам: ждать,
// что продавец, правящий текст письма, знает про формат дат, — это
// не требование, а надежда.
//
// Правило узкое НАМЕРЕННО: только полная ISO-дата целиком, `YYYY-MM-DD`
// и ничего больше. Номер партии `2026-09` или код `12-08-2026` под него
// не попадут — иначе «умное» преобразование начнёт портить данные
// арендатора, а это хуже машинной даты.
const ISO_DAY = /^(\d{4})-(\d{2})-(\d{2})$/

function human(value: string): string {
  const m = ISO_DAY.exec(value)
  return m ? `${m[3]}.${m[2]}.${m[1]}` : value
}

export function render(template: string, payload: Record<string, unknown>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    const v = payload[key]
    return v === null || v === undefined ? '' : human(String(v))
  })
}
