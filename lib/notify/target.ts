// Куда ведёт тап по уведомлению.
//
// ── ЗАЧЕМ ЭТОТ ФАЙЛ ─────────────────────────────────────────────────────────
//
// Обработчик тапа в приложении (`scripts/patch-android.sh`, MainActivity)
// читает `additionalData.url` и открывает этот путь ВНУТРИ веб-вью. Полоска
// уведомления при открытом приложении (`components/banner.tsx`) читает то же
// поле. Оба написаны давно — и оба были мёртвым кодом: `sendPush` отправлял
// только текст, поля `url` не клал никто. То есть тап по боевому пушу
// не вёл никуда, а мастер, получивший «термін придатності: 7 днів», должен
// был сам вспомнить, где смотреть.
//
// ── ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ ЭТО ВАЖНО ───────────────────────────────────────
//
// Адрес кладётся в `data`, а НЕ в поле `url` запроса к OneSignal. Это разные
// вещи, и разница видна на телефоне: `url` — это «открыть в БРАУЗЕРЕ», и
// приложение при таком пуше не открывается вовсе, человек оказывается
// в Chrome с формой входа. Проверено 18.08.2026 на живом устройстве.
// Поэтому в `sendPush` поля `url` нет и заводить его нельзя.
//
// ── ПОЧЕМУ ФУНКЦИЯ, А НЕ КОЛОНКА В ОЧЕРЕДИ ──────────────────────────────────
//
// Соблазн — добавить `notification_outbox.target_url`. Но тогда адрес экрана
// оказывается ЗАМОРОЖЕН в момент постановки в очередь: напоминание за 24 часа
// ставится сегодня, а откроется завтра, и если раздел переехал, ссылка ведёт
// в никуда. Событие и ссылка на сущность — это данные, адрес экрана — это
// код, и он должен считаться в момент отправки.

/** Строки, которыми триггеры помечают источник (0011, 0022, 0085). */
export type RefType = 'booking' | 'container' | 'order' | 'pending' | 'security' | null

/**
 * Путь внутри кабинета, куда ведёт уведомление. Всегда начинается со слэша
 * и НИКОГДА не содержит хоста: хост добавляет приложение, и он обязан быть
 * тем же, на котором открыт веб-вью, — иначе кросс-хостовый переход убивает
 * процесс (та же грабля, что и в `capacitor.config.ts`).
 */
export function pushTarget(event: string, refType: RefType, refId: string | null): string {
  // Сначала событие, потом ссылка на сущность. Событие точнее: у записи
  // и напоминания о ней один и тот же `ref_type`, но человек, получивший
  // «за 2 години», хочет видеть день, а не карточку.
  if (event.startsWith('booking.')) return '/app/bookings'

  if (event.startsWith('order.') || event === 'seller.order_created') {
    return refType === 'order' && refId ? `/app/orders/${refId}` : '/app/orders'
  }

  // Срок годности. Ведём в склад, а не в карточку ёмкости: у мастера
  // с утра их обычно несколько, и список «что истекает» отвечает на вопрос
  // целиком, а карточка — только про одну банку.
  if (event.startsWith('cosmetics.expiry')) return '/app/inventory'

  if (event.startsWith('security.')) return '/app/profile'

  // Незнакомое событие — в кабинет. Пустая строка была бы хуже: обработчик
  // счёл бы её отсутствием адреса и не сделал ничего, а человек всё равно
  // нажал.
  return '/app'
}
