import { DEFAULT_LANG, isLang, LANGS, type Lang } from './dict'

// ── Как язык доходит до серверных компонентов ───────────────────────────────
//
// РЕШЕНИЕ: КУКА `lang`, а не сегмент адреса и не заголовок.
//
// Кабинет — серверные компоненты (правило 3: данные читаются на сервере,
// роль берётся из токена), и хук React там не работает в принципе. Из трёх
// способов остаётся один.
//
//   Сегмент адреса (`/uk/app/team`) отпадает: он переписывает ВСЕ уже
//   существующие адреса. Приглашение выписано на `/invite/<токен>` и лежит
//   в почте у человека; глубокие ссылки обёртки, ссылки в пушах, QR-наклейки
//   на банках, закладки мастеров, `?q=` и `?scan=1` из шапки — всё это
//   пришлось бы либо ломать, либо вечно поддерживать редиректом. Плата
//   огромная, а выигрыш — только там, где адрес должен различать языки для
//   ПОИСКОВИКА. Кабинет закрыт в `app/robots.ts` целиком (`/app/`), то есть
//   этого выигрыша здесь нет вовсе.
//
//   Заголовок `Accept-Language` отпадает как ИСТОЧНИК ПРАВДЫ: он говорит про
//   язык браузера, а не про выбор человека, и выбор в нём не сохранить.
//   Годится максимум как первое предположение для того, кто ещё не выбирал,
//   — но украинский по умолчанию честнее: продукт украинский.
//
// Кука даёт то, чего не даёт localStorage: её ВИДИТ СЕРВЕР. Значит страница
// приходит уже на нужном языке, и кадра с чужим текстом не бывает — та же
// задача, которую тема решает синхронным скриптом (`components/theme.tsx`),
// решённая единственным способом, который работает для серверной отрисовки.
//
// ВИТРИНА — ОТДЕЛЬНЫЙ СЛУЧАЙ, и здесь она сознательно не тронута. Её
// индексируют: одна и та же ссылка, отдающая три языка по куке, для бота
// означает один адрес со случайным содержимым, `hreflang` к нему не
// приделать, и в выдаче окажется тот язык, с которым робот пришёл первым.
// Витрине нужен именно сегмент адреса — и он появится вместе с её
// переделкой (CLAUDE.md → «Внешний вид»: витрина переделывается следующей).
// Каркас к этому готов: `resolveLang` берёт значение откуда угодно, а не
// только из куки.

export const LANG_COOKIE = 'lang'

/** Год. Выбор языка — не сеансовая настройка. */
export const LANG_COOKIE_MAX_AGE = 60 * 60 * 24 * 365

/** Неизвестное или подделанное значение — украинский, без исключений. */
export function resolveLang(raw: string | null | undefined): Lang {
  return isLang(raw) ? raw : DEFAULT_LANG
}

/**
 * Атрибут `lang` на `<html>` до первой отрисовки.
 *
 * Текст в кадре не мигает — его отдаёт сервер, уже прочитав куку. Но корневой
 * макет обслуживает и витрину, и кабинет, и статически рендерится с `lang="uk"`;
 * если его не поправить, скринридер и переносы слов останутся украинскими
 * при русском интерфейсе. Приём — тот же, что у темы: короткий синхронный
 * скрипт в `<head>`, а не эффект после отрисовки.
 */
export const langBootScript =
  `(function(){try{var m=document.cookie.match(/(?:^|; )${LANG_COOKIE}=([^;]*)/);`
  + `var v=m?decodeURIComponent(m[1]):'';`
  + `if(${LANGS.map((l) => `v==='${l}'`).join('||')})document.documentElement.lang=v`
  + `}catch(e){}})()`
