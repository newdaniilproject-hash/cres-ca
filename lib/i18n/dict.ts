import uk from './locales/uk.json'
import ru from './locales/ru.json'
import en from './locales/en.json'

// ── Словари локализации. Где лежат, почему JSON и как называются ключи ──────
//
// РЕШЕНИЕ: словари — ПЛОСКИЕ JSON-файлы с точечными ключами
// (`lib/i18n/locales/<язык>.json`), а не TypeScript-модули.
//
// Почему не TS-модуль. Словарь обязан читаться и вебом, и будущим
// Flutter-приложением (CLAUDE.md → «Общий слой вместо паритета»: правило
// «не забудь продублировать» — признак отсутствующей архитектуры). Из Dart
// файл `.ts` не читается ничем; JSON читается `json.decode` в три строки,
// а плоская карта «ключ → строка» — это ровно формат ARB, который Flutter
// и ждёт от переводчика. Второй копии словаря не будет, потому что копию
// негде завести: файл один и лежит вне кода.
//
// Почему не теряется проверка типов. `resolveJsonModule` в tsconfig уже
// включён, и TypeScript выводит из JSON тип с ТОЧНЫМ набором ключей.
// Отсюда `Key` = объединение всех ключей `uk.json`, и `t('team.invit.title')`
// — ошибка компиляции, а не пустое место на экране. Проверка живёт в том же
// `tsc --noEmit`, что уже стоит в задании «Збірка» и ловит регресс ДО
// слияния. То есть плата за читаемость Flutter — ноль.
//
// Почему плоские ключи, а не вложенные объекты. Вложенность заставила бы
// собирать путь рекурсивным шаблонным типом: он тяжёл, ломается на глубине
// и всё равно не даёт автодополнения по полному пути. Плоская карта отдаёт
// точный union бесплатно и совпадает с ARB.
//
// ── ПРАВИЛО ИМЕНОВАНИЯ КЛЮЧЕЙ (обязательно для всех экранов) ────────────────
//
//   <область>.<блок>.<элемент>[.<состояние или форма>]
//
// Ключ называет СМЫСЛ, а не текст. Переписали формулировку — ключ остался.
// `team.invite.submit`, а не `team.zaprositi`.
//
//   область — экран или сквозная тема: `team`, `settings`, `inventory`,
//             `app` (оболочка), `common` (кнопки и слова, живущие на
//             нескольких экранах), `role` (общий словарь ролей).
//   блок    — секция внутри экрана: `invite`, `templates`, `audit`.
//   элемент — что это за строка. Суффиксы фиксированные:
//             `.title`   заголовок раздела или состояния
//             `.desc`    поясняющий абзац под заголовком
//             `.label`   подпись поля
//             `.hint`    подсказка под полем (`field-hint`)
//             `.placeholder`  подсказка внутри поля
//             `.aria`    подпись для скринридера (`aria-label`)
//             `.submit`  надпись на кнопке действия
//             `.empty.title` / `.empty.desc`  пустое состояние
//             `.error.<причина>`  текст отказа
//   форма   — только для числительных: `.one`, `.few`, `.many`.
//
// Примеры, по которым равняться:
//   inventory.receipt.apply          кнопка «оприбуткувати»
//   inventory.receipt.empty.title    «накладних ще немає»
//   team.block.reason.placeholder    подсказка в поле причины
//   app.chrome.scan.aria             подпись кнопки сканера
//   team.sessions.count.one|few|many «1 сеанс / 2 сеанси / 5 сеансів»
//
// Подстановка — ТОЛЬКО именованная: `«{shop}»`, `«до {date}»`. Порядок слов
// в языках разный, и позиционный `{0}` при переводе на английский собирает
// фразу задом наперёд.
//
// Одинаковый текст на двух экранах НЕ склеивается в один ключ автоматически.
// В `common.*` уезжает только то, что заведомо переводится одинаково всегда:
// «Зберегти», «Скасувати», «Скопіювати». Заголовок раздела «Команда»
// в настройках и в панели — два разных ключа: в другом языке подпись пункта
// меню и заголовок экрана расходятся, и склейка сделает это неисправимым.
//
// ── ЧТО В СЛОВАРЬ НЕ КЛАДЁТСЯ (CLAUDE.md → «Локализация») ───────────────────
//
//   • коды и тексты отказов базы: `error.message` показывается как есть,
//     отказы сторожа (0081) уже написаны по-украински и для человека —
//     переписав их здесь, мы заведём второй источник правды;
//   • служебные значения перечислений: `owner`, `stock.read`, `blocked` —
//     это ключи, а не текст. Переводится ПОДПИСЬ к ним (`role.owner`),
//     само значение остаётся английским всегда;
//   • названия специальностей — справочник `specialities`, переводится
//     данными, а не файлом;
//   • имена языков в переключателе: язык всегда назван на себе самом
//     («Українська», «English»), это не строка интерфейса.

export const LANGS = ['uk', 'ru', 'en'] as const
export type Lang = (typeof LANGS)[number]

/** Умолчание. Украинский — язык продукта, а не «одна из локалей». */
export const DEFAULT_LANG: Lang = 'uk'

export function isLang(v: unknown): v is Lang {
  return typeof v === 'string' && (LANGS as readonly string[]).includes(v)
}

/**
 * Полный набор ключей. Источник — `uk.json`: он собран из существующих строк
 * и по определению полон, `ru` и `en` дописываются позже.
 */
export type Key = keyof typeof uk

/**
 * База ключа числительного: `team.sessions.count` из `…count.one`.
 *
 * Через параметр-посредник, а не `Key extends …` напрямую: условный тип
 * разбирает объединение по членам, только когда слева стоит ГОЛЫЙ параметр.
 * Написанное в лоб проверяло бы всё объединение целиком, давало `never` —
 * и `t.plural` не принимал бы вообще ни одного ключа.
 */
type BaseOfOne<K> = K extends `${infer B}.one` ? B : never
export type PluralKey = BaseOfOne<Key>

/**
 * Проверка неполного словаря на ОПЕЧАТКИ.
 *
 * Просто написать `const ru: Partial<Record<Key, string>>` мало: лишний ключ
 * в объекте, который не является свежим литералом (а импорт JSON им не
 * является), TypeScript пропускает молча — и перевод, набранный с опечаткой,
 * никогда бы не показался, не сломав сборку.
 *
 * Пересечение с `Record<Exclude<keyof T, Key>, never>` требует, чтобы у
 * лишнего ключа был тип `never`, а в JSON там `string`. Нет лишних ключей —
 * `Exclude` даёт `never`, `Record<never, never>` даёт `{}`, и проверка
 * бесплатна.
 */
function checked<T extends Partial<Record<Key, string>>>(
  d: T & Record<Exclude<keyof T, Key>, never>,
): Partial<Record<Key, string>> {
  return d
}

// Все три словаря приезжают в клиентский бандл разом: `DICTS` ссылается на
// каждый. Пока строк несколько сотен, это дешевле, чем ленивая загрузка
// с кадром без текста при переключении. Когда словари вырастут — грузить
// нужный язык динамическим import() в `client.tsx`, а не резать словарь
// по экранам: экраны переиспользуют `common.*` и `role.*`.
export const DICTS: Record<Lang, Partial<Record<Key, string>>> = {
  uk: checked(uk),
  ru: checked(ru),
  en: checked(en),
}
