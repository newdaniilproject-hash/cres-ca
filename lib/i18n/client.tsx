'use client'

import { createContext, useContext, useEffect, useState } from 'react'
import { DEFAULT_LANG, isLang, type Lang } from './dict'
import { createT, type T } from './translate'

// Язык для КЛИЕНТСКИХ компонентов.
//
// Значение приходит сверху пропом от серверного макета, а не читается из
// document.cookie: клиент, читающий куку сам, отрисовал бы первый кадр
// умолчанием и переписал бы его вторым — ровно та вспышка, ради которой
// в теме стоит синхронный скрипт. Сервер уже знает язык, и передать его
// вниз дешевле, чем угадывать.

const LangCtx = createContext<Lang>(DEFAULT_LANG)

export function LangProvider({ lang, children }: { lang: Lang; children: React.ReactNode }) {
  return <LangCtx.Provider value={lang}>{children}</LangCtx.Provider>
}

// ── Провайдер СКВОЗНОГО НИЖНЕГО СТЕКА ──────────────────────────────────────
//
// ЗАДАЧА. До 16.08.2026 провайдер стоял ровно в одном месте — в макете
// кабинета. Всё, что живёт выше или в стороне (вход, `/m`, приглашение,
// кабинет покупателя, а с ними уведомления, полоса связи, предложение
// установки, биометрия), читало контекст с умолчанием и отдавало
// украинский ВСЕГДА. Хуже того, на одной и той же странице серверная
// часть уже звала `getT()` и переключалась, а клиентская рядом — нет:
// половина экрана по-русски, половина по-украински.
//
// Закрытые разделы (`/app`, `(auth)`, `/m`, `/invite`, `/account`) чинятся
// просто: у каждого свой макет, и он ставит `<LangProvider lang={await
// getLang()}>`. Они и так не статические и закрыты в `robots.ts`, так что
// кука там не стоит ничего, зато ПЕРВЫЙ кадр приходит с сервера уже
// на нужном языке.
//
// Остаётся то, у чего своего макета нет и быть не может: НИЖНИЙ СТЕК
// из `components/toast.tsx` — он один на всё приложение и висит над
// любой страницей, включая витрину. Для него и сделан этот провайдер.
//
// ПОЧЕМУ НЕ `getLang()` В КОРНЕВОМ МАКЕТЕ — очевидное решение, которое
// применять нельзя. `cookies()` в корне делает ДИНАМИЧЕСКИМИ все сегменты
// разом, включая витрину: главную, `/t/<slug>`, поиск, карту и правовые
// страницы. Сейчас они статические и отдаются из кэша целиком; это не
// «оптимизация», а причина, по которой витрина выдерживает поисковых
// роботов и всплеск переходов из Instagram.
//
// ПОЧЕМУ НЕ ОБЕРНУТЬ ЭТИМ ПРОВАЙДЕРОМ ВСЁ ДЕРЕВО в корневом макете —
// это было бы проще, но сломало бы чужое решение. Витрина СОЗНАТЕЛЬНО
// закреплена на украинском до переезда на сегмент адреса: её серверные
// части переводит `publicT` (`components/shell.tsx`), а клиентские
// (`map-view`, `booking-flow`) рассчитывают ровно на `DEFAULT_LANG`
// из пустого контекста. Отдай им куку — и на украинской странице
// появился бы русский виджет карты. Язык витрины придёт сегментом
// вместе с её переделкой (`lib/i18n/cookie.ts`), и тогда её макет
// поставит свой провайдер — вложенный всегда сильнее.
//
// ОТКУДА ЗНАЧЕНИЕ. Из `<html lang>`: его синхронно, до первой отрисовки,
// проставляет `langBootScript` в `<head>`. То есть кука доезжает
// до клиента без `cookies()`, без запроса и без второго источника правды.
//
// ЦЕНА, названная честно: значение появляется ВТОРЫМ кадром, после
// монтирования. Читать `<html lang>` прямо в теле отрисовки нельзя —
// сервер такого значения не знает, и React объявил бы это расхождением
// гидратации. Для нижнего стека это ничего не стоит: он пуст, пока
// не случилось событие (пропала сеть, всплыло уведомление, браузер
// предложил установку), — то есть его текста в первом кадре нет вовсе.
// Правило, которое отсюда следует: под этим провайдером не должно
// появиться ничего, что рисует переведённый текст СРАЗУ. Появится —
// ему нужен не этот провайдер, а свой макет с `getLang()`.
//
// ЧЕГО ЭТО НЕ ЧИНИТ: `/auth/finish` (возврат от провайдера) остаётся
// на умолчании, потому что он не переведён вовсе — его заголовки и
// кнопка до сих пор украинские строками. Дать ему язык раньше перевода
// значило бы получить экран, где отказ по-русски, а заголовок над ним
// по-украински.

function docLang(): Lang {
  if (typeof document === 'undefined') return DEFAULT_LANG
  const v = document.documentElement.lang
  return isLang(v) ? v : DEFAULT_LANG
}

export function RootLangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>(DEFAULT_LANG)

  useEffect(() => {
    setLang(docLang())
    // Слушаем сам атрибут, а не куку. Переключатель НЕ перезагружает
    // страницу — он пишет куку, правит `<html lang>` и зовёт
    // `router.refresh()` (`components/lang-switch.tsx`): серверные части
    // приезжают заново, а этот компонент остаётся тем же самым со своим
    // состоянием. Без наблюдателя уведомления и полоса связи так и
    // остались бы на прежнем языке до полной перезагрузки — то есть
    // ровно тот дефект, ради которого всё это и делается.
    const el = document.documentElement
    const obs = new MutationObserver(() => setLang(docLang()))
    obs.observe(el, { attributes: true, attributeFilter: ['lang'] })
    return () => obs.disconnect()
  }, [])

  return <LangCtx.Provider value={lang}>{children}</LangCtx.Provider>
}

export function useLang(): Lang {
  return useContext(LangCtx)
}

/**
 * Переводчик на экране: `const t = useT()`.
 *
 * `useMemo` не нужен — `createT` отдаёт один и тот же объект на язык
 * из своего кэша, и ссылка между отрисовками не меняется.
 */
export function useT(): T {
  return createT(useContext(LangCtx))
}
