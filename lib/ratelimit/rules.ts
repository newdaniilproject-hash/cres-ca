// Таблица «путь → предел». Одна на весь проект, повторяет ту, что стоит
// на Cloudflare: два ограничителя, расходящиеся в числах, — это два разных
// ограничителя, и через полгода никто не скажет, какой из них сработал.
//
// Числа дословно из плана:
//
//   Вход и восстановление   5 за 15 хвилин
//   Регистрация             3 за годину
//   Заказ и запись          10 за годину
//   Публичный поиск         60 за хвилину
//   Любой путь              300 за хвилину

export type Scope = 'signin' | 'signup' | 'order' | 'search' | 'any'

export type Limit = { max: number; windowMs: number }

// ⚠️ Чем эти числа рискуют, и это надо знать до, а не после. Считаем
// по адресу, а мобильные операторы Украины выпускают абонентов через общий
// адрес (CGNAT): десятки людей на одном IPv4 делят одно ведро. Предел
// «3 регистрации за час» на таком адресе означает, что четвёртый покупатель
// с того же оператора в тот же час не зарегистрируется. Числа взяты из плана
// дословно и здесь не смягчаются, но если на бою появятся отказы у живых
// людей — смотреть надо сюда, а не искать поломку. В журнале такой случай
// виден: подряд идущие отказы `signup` с одного адреса и разных сеансов.
export const LIMITS: Record<Scope, Limit> = {
  signin: { max: 5, windowMs: 15 * 60_000 },
  signup: { max: 3, windowMs: 60 * 60_000 },
  order: { max: 10, windowMs: 60 * 60_000 },
  search: { max: 60, windowMs: 60_000 },
  any: { max: 300, windowMs: 60_000 },
}

// ── Что НЕ ограничивается ───────────────────────────────────────────────────
//
// `/api/cron/*` — у них своя защита (`CRON_SECRET`), и ограничивать их
// нельзя не «из вежливости», а по факту: расписание живёт в `pg_cron` внутри
// Supabase и стучится СЕМЬЮ разными адресами раз в минуту с ОДНОГО адреса
// Supabase (видно в журнале Vercel за 16–17.08.2026). Под общим счётчиком
// «любой путь» они делят одно ведро с чем угодно, что придёт с того же
// адреса, а отказ расписанию — это не 429 на экране, а неотправленные
// напоминания, которых никто не хватится.
//
// `/.well-known/*` — проверка App Links Android и Universal Links iOS.
// Отказ здесь означает, что ссылки перестают открываться в приложении,
// причём не сразу, а при следующей проверке системой.
//
// Статика — файлы с расширением и `/_next/*`. Часть их уже отсечена
// сопоставителем в `proxy.ts`, но не вся: `sw.js`, `manifest.webmanifest`,
// `offline.html` и `_next/data` проходят. Одна страница витрины — это
// десятки таких запросов, и под пределом 300/хв ими одними человек
// выбрал бы своё ведро за минуту нормальной работы.
// `/api/health` в списке НЕТ намеренно: сторож зовёт его раз в несколько
// минут и до предела 300/хв не достаёт даже близко, а это единственный
// открытый адрес, который ходит в базу, — оставлять его без счёта было бы
// странно. Если сторож когда-нибудь получит 429, это будет ложная тревога,
// и тогда адрес переедет сюда.
const NEVER = [
  /^\/api\/cron\//,
  /^\/\.well-known\//,
  /^\/_next\//,
]

/** Расширение в последнем сегменте пути — признак файла, а не экрана. */
const FILE = /\/[^/]+\.[a-z0-9]{2,5}$/i

const SIGNIN = [/^\/login(?:\/|$)/, /^\/forgot(?:\/|$)/, /^\/reset(?:\/|$)/, /^\/m\/login(?:\/|$)/]
const SIGNUP = [/^\/register(?:\/|$)/, /^\/m\/register(?:\/|$)/]
const ORDER = [/^\/t\/[^/]+\/book(?:\/|$)/]
const SEARCH = [/^\/search(?:\/|$)/, /^\/map(?:\/|$)/]

const hits = (path: string, list: RegExp[]) => list.some((r) => r.test(path))

/**
 * Какие счётчики тратит запрос.
 *
 * Пустой список означает «не ограничиваем».
 *
 * ── Почему узкие пределы НЕ применяются к обычному открытию страницы ───────
 *
 * Предел входа — 5 за 15 хвилин. Если считать им ПОКАЗЫ `/login`, то человек,
 * который сходил «вхід → реєстрація → забули пароль → назад» пять раз,
 * получает отказ на форме входа, ничего ни разу не отправив. Узкие пределы
 * считают ПОПЫТКИ: всё, что не GET и не HEAD. Показ страницы попадает под
 * общий предел «любой путь», как и любая другая страница.
 *
 * ── Почему серверные действия здесь пропускаются ───────────────────────────
 *
 * Серверное действие Next — это POST на адрес самой страницы с заголовком
 * `next-action`. Форма входа зовёт `guardSignIn()` (`lib/ratelimit/guard.ts`),
 * которое тратит счётчик `signin` ЯВНО и по смыслу. Посчитать его ещё раз
 * здесь по пути `/login` значило бы списывать две попытки за одну, то есть
 * молча превратить предел 5 в предел 2.
 */
export function scopesFor(path: string, method: string, isServerAction: boolean): Scope[] {
  if (NEVER.some((r) => r.test(path)) || FILE.test(path)) return []

  const out: Scope[] = ['any']
  if (hits(path, SEARCH)) out.push('search')

  const attempt = method !== 'GET' && method !== 'HEAD' && !isServerAction
  if (attempt) {
    if (hits(path, SIGNIN)) out.push('signin')
    else if (hits(path, SIGNUP)) out.push('signup')
    else if (hits(path, ORDER)) out.push('order')
  }

  return out
}
