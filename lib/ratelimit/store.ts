// Где живут счётчики. Решение, причина и — обязательно — чего оно НЕ даёт.
//
// ════════════════════════════════════════════════════════════════════════════
// РЕШЕНИЕ: счётчики живут в ПАМЯТИ экземпляра, а не в Postgres.
// ════════════════════════════════════════════════════════════════════════════
//
// ── Что было на выбор ──────────────────────────────────────────────────────
//
// 1. Postgres, который уже есть: таблица счётчиков и атомарная функция.
//    Ничего не подключать, счётчик общий на все экземпляры, переживает
//    холодный старт.
// 2. Сторонний ключ-значение (Upstash и подобные). Отпадает по ADR 0007:
//    это третий сервис, третий счёт и третье место для переменных окружения,
//    а решение о постоянном хранилище принимается «не если станет медленно,
//    а по конкретному признаку» и отдельным ADR.
// 3. Память процесса.
//
// ── Почему НЕ Postgres. Это измерено, а не прикинуто ───────────────────────
//
// Приложение развёрнуто в `iad1` (Вашингтон), база Supabase — в `eu-west-1`
// (Ирландия). Один вызов функции базы через PostgREST на этом плече стоит
// НЕ единиц миллисекунд, а сотен. Замер боевого `/api/health`, 17.08.2026:
// проверка `database` — это ровно один вызов `active_cities` (короткий
// список городов, никакой работы) — заняла 476 мс и 401 мс на двух подряд
// запросах к живому домену.
//
// Ограничитель на Postgres означает такой вызов ПЕРЕД каждым запросом,
// последовательно, до начала отрисовки. Сверяемся с `docs/PERFORMANCE.md`:
//
//   переход между экранами кабинета   цель 100 мс, предел 300 мс
//   первый показ страницы витрины     цель 1 с,    предел 2,5 с
//
// То есть проверка предела сама по себе в четыре раза дороже ЦЕЛИ перехода
// по кабинету и выше его ПРЕДЕЛА. Это не «дороговато» — это выход за бюджет
// приёмки одним действием, ещё до того как страница начала собираться.
// И это ровно правило 3 оттуда же: «запросы не выстраиваются в цепочку» —
// а проверка в `proxy.ts` не распараллеливается ни с чем в принципе.
//
// Второе, помимо задержки: под пределом «любой путь 300/хв» КАЖДЫЙ просмотр
// витрины становится ЗАПИСЬЮ в базу. Пятьдесят человек, листающих каталог, —
// это порядка тысячи записей в минуту в таблицу счётчиков, с WAL, распуханием
// и автовакуумом, на той же базе, которая обязана отдать список за 50 мс.
// Мы завели бы себе нагрузку ради защиты от нагрузки.
//
// ── Что даёт память ────────────────────────────────────────────────────────
//
// Ноль миллисекунд, ноль инфраструктуры, ноль записей в базу. Ловит то, чем
// злоупотребление выглядит на практике чаще всего: один адрес, много
// запросов подряд, короткое время. Такая очередь запросов почти целиком
// попадает в один тёплый экземпляр — тот, который платформа уже держит
// открытым, — поэтому счётчик её видит.
//
// ════════════════════════════════════════════════════════════════════════════
// ⚠️ ЧЕГО ЭТО НЕ ДАЁТ. Прямо, как в `app/api/team/invite/route.ts`
// ════════════════════════════════════════════════════════════════════════════
//
// 1. ЛИМИТ НЕ ОБЩИЙ. Память живёт в ОДНОМ экземпляре функции. Платформа
//    поднимает их столько, сколько нужно под нагрузку, и запросы одного
//    адреса могут разойтись по разным. Настоящий потолок — «предел ×
//    количество живых экземпляров», а не предел. Число экземпляров нам
//    неизвестно и не управляемо.
// 2. ХОЛОДНЫЙ СТАРТ ОБНУЛЯЕТ СЧЁТ. Экземпляр, который платформа погасила
//    за простоем, уносит счётчики с собой. Предел «3 регистрации за час»
//    после паузы начинается заново.
// 3. РАСПРЕДЕЛЁННАЯ АТАКА НЕ ЛОВИТСЯ ВООБЩЕ. Тысяча адресов по десять
//    запросов не превысит ни одного предела. Это задача Cloudflare, и она
//    там и решается; здесь — второй заслон на случай, когда Cloudflare
//    обойдён (а обойти его можно уже сегодня: домен `*.vercel.app` отвечает
//    напрямую, см. `address.ts`).
// 4. ЭТО НЕ ВИДИТ ТОГО, ЧТО ИДЁТ МИМО ПРИЛОЖЕНИЯ. Вход, регистрация,
//    восстановление пароля и создание записи выполняются из БРАУЗЕРА прямо
//    в Supabase (`app/(auth)/*`, `app/m/*`, `booking-flow.tsx` зовут
//    `supabase.auth.*` и `supabase.rpc(...)` клиентским кодом). Эти запросы
//    не приходят ни на Vercel, ни на Cloudflare — их не видит ни один из
//    двух ограничителей, о которых говорит план. Наш `guard.ts` закрывает
//    их со стороны интерфейса, но обходится одной строкой скрипта, который
//    зовёт Supabase напрямую. Единственное место, где этот предел
//    ДЕЙСТВИТЕЛЬНО можно применить, — сам Supabase: настройки Auth Rate
//    Limits в панели и проверка внутри функций `create_booking` /
//    `create_order`. См. отчёт по шагу 6.
//
// ════════════════════════════════════════════════════════════════════════════

export type Hit = { ok: true } | { ok: false; retryAfterMs: number }

type Bucket = { n: number; resetAt: number }

// Потолок на количество ключей. Без него ограничитель сам становится
// уязвимостью: перебор адресов (в IPv6 это бесплатно) наращивал бы карту,
// пока экземпляру не кончится память. При переполнении НОВЫЕ ключи не
// заводятся и запрос пропускается — отказывать всем из-за нехватки места
// значит уронить сайт тем самым механизмом, который его защищает.
const MAX_KEYS = 20_000

// Уборка — не по таймеру: таймер в бессерверной функции не выполняется,
// пока не пришёл запрос, и держит экземпляр живым. Убираем по ходу дела,
// не чаще раза в минуту, тем же приёмом, что и в роуте приглашения.
const SWEEP_EVERY_MS = 60_000

type State = { buckets: Map<string, Bucket>; sweptAt: number; full: boolean }

// На `globalThis`, а не модульной константой: при горячей перезагрузке
// в разработке и при двух сборках одного модуля (серверной и для `proxy`)
// модульное состояние удваивается, и предел молча становится вдвое мягче.
const g = globalThis as typeof globalThis & { __ratelimit?: State }
const state: State = (g.__ratelimit ??= { buckets: new Map(), sweptAt: 0, full: false })

function sweep(now: number): void {
  for (const [k, b] of state.buckets) if (now >= b.resetAt) state.buckets.delete(k)
  state.sweptAt = now
}

/**
 * Потратить одно обращение из ведра `key`.
 *
 * Окно ФИКСИРОВАННОЕ, а не скользящее: скользящее требует хранить отметки
 * времени каждого обращения, то есть в 300 раз больше памяти на ведро
 * «любой путь». Плата за фиксированное окно названа честно: на стыке двух
 * окон подряд проходит до двух пределов за раз (5 в конце одного и 5
 * в начале следующего). Для заслона от долбёжки это несущественно, для
 * настоящей защиты — тем более, потому что настоящую даёт не этот файл.
 */
export function hit(key: string, limit: { max: number; windowMs: number }, now = Date.now()): Hit {
  if (now - state.sweptAt >= SWEEP_EVERY_MS) sweep(now)

  const b = state.buckets.get(key)

  if (b && now < b.resetAt) {
    b.n += 1
    if (b.n > limit.max) return { ok: false, retryAfterMs: b.resetAt - now }
    return { ok: true }
  }

  if (!b && state.buckets.size >= MAX_KEYS) {
    sweep(now)
    if (state.buckets.size >= MAX_KEYS) {
      if (!state.full) {
        state.full = true
        console.warn(
          `[ratelimit] карта счётчиков заполнена (${MAX_KEYS} ключей) — новые адреса`
          + ' пропускаются без ограничения. Это признак перебора адресов:'
          + ' настоящий заслон в этом случае — Cloudflare, а не приложение.',
        )
      }
      return { ok: true }
    }
    state.full = false
  }

  state.buckets.set(key, { n: 1, resetAt: now + limit.windowMs })
  return { ok: true }
}
