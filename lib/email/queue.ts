import { emailLayout, escapeHtml, type EmailButton } from './layout'
import { abs } from '@/lib/site'

// Вёрстка для писем ИЗ ОЧЕРЕДИ уведомлений (app/api/cron/notifications).
//
// Зачем отдельный файл, а не готовые письма из templates.ts. Тексты
// событий живут в базе (`notification_templates`, 0011): «событие
// описывается один раз», и арендатор может завести свой текст вместо
// платформенного. Если бы очередь брала тело из кода, переопределение
// арендатора молча игнорировалось бы — а в письме оказались бы два
// разных текста: свой в HTML и чужой в запасном текстовом теле.
// Поэтому делится так: база даёт ТЕКСТ, этот файл — КАРКАС.
//
// Что это даёт: письма о заказах, записях, напоминаниях и сроках
// годности перестают уходить голой строкой без темы оформления и
// приезжают в том же виде, что приглашение в команду. Текст никуда
// не девается — он уходит вторым телом письма для читалок, которые
// HTML не разбирают (и он же ложится в предпросмотр).

// Кнопка в письме. Только там, где страница РЕАЛЬНО существует и
// получатель имеет к ней доступ. Письма покупателю кнопок не получают
// намеренно: публичного экрана заказа и экрана переноса записи
// в проекте нет, а кнопка в никуда хуже её отсутствия.
const BUTTONS: Record<string, EmailButton> = {
  'seller.order_created':   { label: 'Відкрити замовлення', url: abs('/app/orders') },
  'seller.booking_created': { label: 'Відкрити запис',      url: abs('/app/bookings') },
  'cosmetics.expiry_14d':   { label: 'Відкрити склад',      url: abs('/app/inventory') },
  'cosmetics.expiry_7d':    { label: 'Відкрити склад',      url: abs('/app/inventory') },
}

/**
 * HTML для письма очереди: подставленные тема и текст → каркас письма.
 *
 * `subject` и `text` приходят уже после подстановки плейсхолдеров, то
 * есть содержат данные от пользователя — имя клиента, название заведения,
 * причину отмены. Всё экранируется: иначе заведение с угловой скобкой
 * в названии ломает вёрстку чужого письма, а то и подставляет свою.
 */
export function queueEmailHtml(event: string, subject: string, text: string): string {
  // Абзацы по переводам строки: шаблон в базе — обычный текст, и
  // единственная разметка, которая в нём есть, — это перенос строки.
  const lines = text.split(/\r?\n/).map((l) => l.trim()).filter((l) => l.length > 0)

  // Тема может быть пустой: у шаблонов push-канала `subject` вообще
  // null, и правка шаблона легко оставляет пустую строку. Тогда
  // заголовком становится первая строка текста, иначе письмо приезжает
  // с пустым заглавием.
  const trimmedSubject = subject.trim()
  const heading = trimmedSubject || lines[0] || 'CRES-CA'
  const rest = trimmedSubject ? lines : lines.slice(1)
  const paragraphs = rest.length > 0 ? rest : [heading]

  return emailLayout({
    // Превью в списке писем: первая строка тела, а не тема — тему
    // почтовик и так показывает рядом, дублировать её незачем.
    preheader: paragraphs[0] ?? heading,
    heading,
    body: paragraphs
      .map((p) => `<p style="margin:0 0 12px;">${escapeHtml(p)}</p>`)
      .join(''),
    button: BUTTONS[event],
  })
}
