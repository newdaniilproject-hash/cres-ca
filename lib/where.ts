import type { SupabaseClient } from '@supabase/supabase-js'

// Куда вести человека после входа. Одно место на всё приложение,
// чтобы экран приветствия и экран кода не расходились в решении.
//
// Нет сессии → приветствие. Есть заведение → кабинет. Нет заведения —
// развилка по тому, КЕМ человек регистрировался (`profiles.intent`,
// миграция 0118): продавца ведём достраивать заведение, покупателя —
// в его кабинет.
//
// ⚠️ ЧТО ЗДЕСЬ БЫЛО СЛОМАНО (починено 19.08.2026). Развилки не было
// вовсе: «нет заведения» вело на создание заведения ВСЕХ. Регистрация
// покупателя при этом существует отдельным экраном, покупательский
// кабинет существует, связи в базе есть — а человек, зарегистрировавшийся
// покупателем, при следующем входе видел «створіть заклад» и попадал
// в свой кабинет только по прямой ссылке. Клиентский сценарий ломался
// на первом же шаге.
//
// Почему не «нет заведения → всегда /account»: продавец, прервавший
// регистрацию на шаге заведения, находится в ТОМ ЖЕ состоянии (сессия
// есть, членства нет), и без признака он терял бы свой онбординг.
// Разбор — в шапке миграции 0118.
//
// Поверхностей две — веб и приложение (/m), — и различаются они ТОЛЬКО
// адресами: решение («нет сессии / нет заведения / есть заведение»)
// у них общее. Поэтому здесь таблица адресов, а не вторая копия функции:
// правило «не забудь продублировать» — признак отсутствующей архитектуры.
//
// `account` у обеих поверхностей один: покупательский кабинет живёт вне
// /m, потому что /m — это оболочка продавца, и второй его копии
// для покупателя не существует.
const ROUTES = {
  web: { anon: '/login', shop: '/register/seller', app: '/app', account: '/account' },
  m: { anon: '/m', shop: '/m/shop', app: '/app', account: '/account' },
} as const

export type Surface = keyof typeof ROUTES

/**
 * Куда падать ПОСЛЕ ВЫХОДА.
 *
 * ⚠️ Все три кнопки «Вийти» (панель, шторка под аватаром, профиль) вели
 * на `/` — то есть на продающую главную. Человек, который только что
 * вышел из кабинета, получал рекламу «Одна підписка замість чотирьох
 * сервісів» вместо формы входа, а в обёртке — ещё и вид сайта внутри
 * приложения (найдено 20.08.2026 на устройстве).
 *
 * Выход — это не «ушёл с сайта», а «хочу войти другим». Поэтому ведём
 * на вход той поверхности, с которой вышли: в обёртке — приветствие
 * приложения, в браузере — веб-вход. Главная остаётся тем, чем она
 * и является: страницей для тех, кто пришёл впервые.
 *
 * Признак читается атрибутом, а не через `nativeish()`: тот живёт
 * в клиентском модуле, а этот файл зовут и серверные. Атрибут ставится
 * до первой отрисовки (`native-boot.ts`) и на Android он единственный
 * надёжный — моста Capacitor там при удалённом `server.url` нет.
 */
export function afterSignOut(): string {
  const native = typeof document !== 'undefined'
    && document.documentElement.hasAttribute('data-native')
  return native ? ROUTES.m.anon : ROUTES.web.anon
}

export async function nextRoute(
  supabase: SupabaseClient,
  // По умолчанию — приложение: так эту функцию звали до появления веба,
  // и все вызовы из /m остаются без аргумента.
  surface: Surface = 'm',
): Promise<string> {
  const routes = ROUTES[surface]

  const { data } = await supabase.auth.getSession()
  if (!data.session) return routes.anon

  const { data: rows, error } = await supabase
    .from('tenant_members')
    .select('tenant_id')
    .limit(1)

  // Ошибку чтения не превращаем в тупик: пустим в кабинет,
  // он сам разберётся и отправит куда надо (app/app/page.tsx
  // без членства делает redirect на создание заведения).
  if (error) return routes.app
  if (rows && rows.length > 0) return routes.app

  // Заведения нет — читаем признак регистрации. Запрос делается ТОЛЬКО
  // на этой ветке: у того, у кого заведение есть, признак не читается
  // вовсе, а это подавляющее большинство входов.
  //
  // Отсутствие строки или отказ чтения трактуем как продавца: это
  // прежнее поведение, и ошибиться в его сторону дешевле — продавец
  // из своего онбординга дойдёт до конца, а покупатель, попавший
  // на создание заведения, просто уйдёт по ссылке в кабинет.
  const { data: profile } = await supabase
    .from('profiles')
    .select('intent')
    .single()

  return profile?.intent === 'buyer' ? routes.account : routes.shop
}
