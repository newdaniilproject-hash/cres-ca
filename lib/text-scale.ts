// Множитель размера текста: значения и загрузочный скрипт.
//
// Вынесено из `components/text-size.tsx` по тому же правилу, что и тема
// (`lib/theme-script.ts`): всё, что читает или зовёт СЕРВЕР, живёт
// в модуле без `'use client'`. Скрипт отдаёт разметкой корневой макет,
// то есть серверный компонент.
//
// Здесь это ещё не падало — строку из клиентского модуля прочитать
// можно, вызвать функцию нельзя, — но держать значение по ту сторону
// границы значит оставлять ловушку: следующий, кому понадобится
// вычислить скрипт по параметру, сделает из константы функцию и уронит
// бой ровно так же, как это случилось с темой 19.08.2026.

/** Ключ в localStorage. */
export const SCALE_KEY = 'text-scale'

// 0.9 — нижняя граница: ниже поля ввода упёрлись бы в свой пол 16px,
// и дальнейшее уменьшение перестало бы что-либо менять в формах.
// 1.4 — верхняя: на 390px заголовок раздела в две строки ещё читается.
export const SCALE_MIN = 0.9
export const SCALE_MAX = 1.4
export const SCALE_STEP = 0.05

// Синхронно в <head>, ДО первой отрисовки, ровно как у темы. Иначе первый
// кадр рисуется прежним размером, и человек с крупным шрифтом видит,
// как страница дёргается и переверстывается у него на глазах.
export const textScaleBootScript =
  `(function(){try{var v=parseFloat(localStorage.getItem('${SCALE_KEY}'));`
  + `if(v&&v>=${SCALE_MIN}&&v<=${SCALE_MAX}&&v!==1)`
  + `{document.documentElement.style.setProperty('--type-scale',String(v))}}catch(e){}})()`
