// Тема как ЗНАЧЕНИЕ и как загрузочный скрипт.
//
// ⚠️ ЭТОТ ФАЙЛ НАМЕРЕННО БЕЗ `'use client'`, и это не мелочь оформления.
// Его читают ОБА мира: серверные макеты (`app/layout.tsx`,
// `app/app/layout.tsx`) отдают отсюда строку скрипта в разметку,
// а клиентский переключатель (`components/theme.tsx`) — те же значения.
//
// Оплачено падением боя 19.08.2026. `themeServerScript` жил в
// `components/theme.tsx` с директивой `'use client'`, а звал его
// серверный макет кабинета. Любой экспорт клиентского модуля на сервере
// — это не функция, а ссылка на клиентскую сущность, и вызов её
// заканчивается «Attempted to call themeServerScript() from the server».
// Сборка при этом ЗЕЛЁНАЯ: ошибка рантайма, а не типов, — и весь
// кабинет отдавал 500 на каждой странице.
//
// Правило, которое отсюда следует: всё, что зовёт СЕРВЕР, живёт в модуле
// без `'use client'`. Клиентский файл может это импортировать, обратное —
// нет.

export type Choice = 'light' | 'dark'

/** Ключ в localStorage. Он же имя в загрузочном скрипте. */
export const THEME_KEY = 'theme'

// Цвет шапки браузера на телефоне обязан идти за темой. Он задан
// в разметке одним значением (умолчание), и без правки человек,
// переключившийся в тёмную, видит светлую полосу над чёрной страницей —
// ровно тот стык, из-за которого страница выглядит сломанной.
export const THEME_BAR = { light: '#f4f5f7', dark: '#0c0e13' } as const

// Исполняется ДО первой отрисовки, синхронно в <head>. Иначе первый кадр
// рисуется умолчанием, и человек с тёмной темой видит вспышку белого.
export const themeBootScript =
  `(function(){try{var t=localStorage.getItem('${THEME_KEY}');`
  + `if(t==='dark'){document.documentElement.classList.add('dark')}}catch(e){}})()`

// Тема, известная СЕРВЕРУ (из `profiles.theme`), применяется до первого
// кадра кабинета. Скрипт возвращается разметкой макета и исполняется
// на месте. Эффектом это делать нельзя: эффект случается ПОСЛЕ отрисовки,
// и человек, выбравший тёмную тему на телефоне, увидел бы на вебе белую
// вспышку и перекраску.
//
// localStorage правится тем же скриптом — иначе следующая загрузка снова
// начнётся с устаревшего значения и вспышка вернётся.
export function themeServerScript(choice: Choice) {
  return `(function(){try{`
    + `var c=${JSON.stringify(choice)};`
    + `document.documentElement.classList.toggle('dark',c==='dark');`
    + `localStorage.setItem('${THEME_KEY}',c);`
    + `var m=document.querySelector('meta[name="theme-color"]');`
    + `if(m)m.setAttribute('content',c==='dark'?'${THEME_BAR.dark}':'${THEME_BAR.light}');`
    + `}catch(e){}})()`
}
