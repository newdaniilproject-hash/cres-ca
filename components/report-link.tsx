'use client'

import { useCallback } from 'react'

// ── Посилання на документ, який відкривається окремою сторінкою ─────────────
//
// ЗАЧЕМ ЭТОТ КОМПОНЕНТ. Отчёт для Держпродспоживслужби и лист наклеек —
// не экраны кабинета, а ДОКУМЕНТЫ: отдельные HTML-страницы, которые печатают.
// В браузере их правильно открывать новой вкладкой (`target="_blank"`),
// чтобы кабинет остался на месте.
//
// ⚠️ НО В ОБЁРТКЕ `target="_blank"` — ЭТО ЛОВУШКА, и это тот же класс
// граблей, что и `url` у пуша (`lib/notify/target.ts`): «открыть в новом
// окне» веб-вью Capacitor понимает как «отдать системному браузеру».
// А в системном браузере СЕССИИ НЕТ — куки живут в банке веб-вью, не общей
// с Chrome или Safari того же телефона (то же соображение, из-за которого
// тема хранится в `profiles`, а не в `localStorage`). Мастер жмёт «Звіт
// для перевірки» при инспекторе — и получает форму входа в чужом браузере.
//
// Риск назван независимым аудитом ТЗ 25.08.2026 и здесь снят по признаку,
// а не наугад: в обёртке уходим в ТО ЖЕ окно (`window.location`), в вебе
// оставляем вкладку. Возврат в обёртке — системный жест «назад» и стрелка
// шапки, которые и так работают на любой странице.
//
// Признак — атрибут `data-native` на <html>, а не мост Capacitor: на Android
// при удалённом `server.url` моста НЕТ (КОНСПЕКТЫ.md, М6), атрибут же
// ставится до первой отрисовки в `native-boot.ts`.
export function ReportLink({
  href, className, children,
}: {
  href: string
  className?: string
  children: React.ReactNode
}) {
  const open = useCallback((e: React.MouseEvent<HTMLAnchorElement>) => {
    const native = document.documentElement.hasAttribute('data-native')
    if (!native) return // веб: пусть браузер откроет вкладку сам
    e.preventDefault()
    window.location.href = href
  }, [href])

  // `target` и `rel` остаются в разметке: до гидратации обработчика нет,
  // и нажатие в эту миллисекунду обязано вести себя как в вебе, а не
  // никак. В обёртке первый же клик после гидратации пойдёт по ветке выше.
  return (
    <a href={href} target="_blank" rel="noreferrer" className={className} onClick={open}>
      {children}
    </a>
  )
}
