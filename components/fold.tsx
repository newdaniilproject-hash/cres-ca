'use client'

import { useId } from 'react'
import { IconChevronRight } from '@/components/icons'

// ── Сворачиваемая секция экрана ─────────────────────────────────────────────
//
// Вынесена из экрана склада 25.08.2026, когда та же механика понадобилась
// карточке засоба. Разметку там писали по месту, и второй такой же блок
// в другом файле разъехался бы с первым на первой правке: у липкого
// подзаголовка есть отступ сверху (`--apphead-h`), поворот стрелки
// и зона нажатия — три величины, которые обязаны совпадать на всех
// экранах, иначе секции «прыгают» при переходе между ними.
//
// ПРАВИЛО ОДНОЙ ОТКРЫТОЙ живёт у РОДИТЕЛЯ, а не здесь: компонент не знает
// о соседях и не должен. Родитель держит ключ раскрытой секции и передаёт
// `open` — так же, как это сделано на складе.
//
// Зачем это вообще (требование владельца 25.08.2026): экран, где восемь
// секций лежат одна под другой, — это полотно, по которому листают вслепую.
// Свёрнутые секции превращают его в оглавление: видно, что есть, и видно,
// сколько внутри.
export function Fold({
  title, count, open, onToggle, tone, children,
}: {
  title: string
  /** Сколько внутри. Без числа заголовок не отвечает «стоит ли открывать». */
  count?: number
  open: boolean
  onToggle: () => void
  /** Красная точка у секции, которая просит внимания. */
  tone?: 'alert'
  children: React.ReactNode
}) {
  // Связка «заголовок ↔ содержимое» для незрячего. `aria-expanded` говорит
  // только «раскрыто», но НЕ говорит, что именно раскрылось: на экране
  // с десятью секциями подряд скринридер объявлял «кнопка, раскрыта»,
  // и дальше человек шёл по строкам, не понимая, к какой секции они
  // относятся. `aria-controls` называет область, `role="region"` делает
  // её остановкой в списке ориентиров, `aria-labelledby` возвращает ей
  // имя секции. Это единственное, что взято из присланного
  // radix-аккордеона (30.08.2026), — и взято кодом, а не библиотекой:
  // три атрибута против трёх зависимостей.
  //
  // `useId`, а не счётчик и не индекс: идентификатор обязан совпасть
  // между отрисовкой на сервере и в браузере, иначе React ругается
  // на расхождение разметки, а связка молча рвётся.
  const id = useId()

  return (
    <div className="flex flex-col gap-2">
      <button type="button" className="group-head" id={`${id}-head`}
              aria-expanded={open} aria-controls={`${id}-body`} onClick={onToggle}>
        {tone === 'alert' && (
          <span aria-hidden className="hero-dot" style={{ background: 'var(--tone-rose)' }} />
        )}
        <span className="group-head-title">{title}</span>
        {count != null && (
          <span className="count-pill shrink-0" style={{ color: 'var(--color-muted)' }}>
            {count}
          </span>
        )}
        <span className="group-caret"><IconChevronRight size={16} /></span>
      </button>
      {/* Содержимое РАЗМОНТИРУЕТСЯ, а не прячется стилем, и это отличие
          от radix намеренное: на складе внутри секции лежат сотни строк
          реєстру со своими обработчиками, и держать в DOM девять закрытых
          секций ради анимации высоты — плата, которой мы не хотим.
          Область остаётся в разметке пустой, чтобы `aria-controls`
          не указывал в никуда, когда секция закрыта. */}
      {/* Две величины, каждая из которых ломает вид, если её забыть.
          Обе проверены попыткой обойтись без них.

          1. `flex flex-col gap-2` — ОБЯЗАТЕЛЬНЫ. До появления области
             содержимое лежало прямыми детьми внешнего контейнера
             и разделялось ЕГО зазором; обёртка без своего зазора
             склеила бы соседей — например подпись и сетку галочек
             в карточке участника («Команда»), где детей двое.

          2. `hidden` НА ЗАКРЫТОЙ, и класс раскладки СНИМАЕТСЯ вместе
             с ним. Область обязана существовать в разметке всегда,
             иначе `aria-controls` заголовка указывает в никуда; но
             пустой блок остаётся ребёнком внешнего flex-контейнера,
             и его зазор в 8px повисает под КАЖДЫМ закрытым заголовком
             — на экране с девятью секциями это семьдесят два пикселя
             пустоты ровно того рода, что владелец уже просил убрать.
             Атрибута `hidden` тут мало: `display:flex` из класса
             перебивает `display:none` таблицы браузера, и блок остаётся
             в потоке. Поэтому у закрытой секции класса нет вовсе. */}
      <div id={`${id}-body`} role="region" aria-labelledby={`${id}-head`}
           hidden={!open} className={open ? 'flex flex-col gap-2' : undefined}>
        {open && children}
      </div>
    </div>
  )
}
