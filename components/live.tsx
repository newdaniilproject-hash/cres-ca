'use client'

import { useEffect, useTransition } from 'react'
import { useRouter } from 'next/navigation'
import { createClient } from '@/lib/supabase/client'

// Живі дані: змінилось будь-що в закладі — екран оновився сам.
//
// ── ЩО ПРОСИЛИ ─────────────────────────────────────────────────────────────
//
// Власник 25.08.2026: «зроби миттєвість повністю і правильно, без милиць,
// щоб працювало ЗАВЖДИ, а не тільки на тих екранах, де я часто працюю,
// і робота з різних пристроїв синхронізувалась миттєво».
//
// ── ЩО БУЛО ────────────────────────────────────────────────────────────────
//
// Оболонка перезапитувала вміст при поверненні в застосунок і не частіше
// (`components/app-shell.tsx`). Це закриває «згорнув — розгорнув», але не
// закриває головне: адміністратор за столом завів позицію, а майстер
// із телефоном у залі бачить старе, поки не згорне застосунок. Двоє
// людей в одному закладі бачили різні дані, і жоден із них не знав,
// хто саме бачить старе.
//
// ── ЧОМУ ОДНА ПІДПИСКА, А НЕ ПО ПІДПИСЦІ НА ЕКРАН ──────────────────────────
//
// Очевидний шлях — на кожному екрані підписатись на свої таблиці. Це
// і є та «милиця», якої просили не робити: працює рівно там, де хтось
// не полінувався дописати, новий екран оживає лише після того, як про
// нього згадали, а забути можна мовчки — все працює, просто не миттєво.
//
// Тут інакше: база тримає ОДИН лічильник на заклад (`tenant_pulse`,
// міграція 0133), і будь-яка зміна будь-де його підіймає. Застосунок
// слухає одну таблицю з одним фільтром, а екран просто перезапитує себе.
// Новому екрану не треба нічого: він читає ті самі таблиці, а вони вже
// пульсують.
//
// ── ЧОМУ ЦЕ БЕЗПЕЧНО ДЛЯ ТОГО, ХТО ЗАРАЗ ПРАЦЮЄ ────────────────────────────
//
// `router.refresh()` — не перезавантаження сторінки. Він перезапитує
// лише серверну частину; стан клієнта лишається на місці: відкрита
// шторка не закривається, набране в полі не стирається, прокрутка
// не стрибає. Саме тому тут не потрібне те огородження, що стоїть
// у `components/pwa.tsx` для НОВОЇ ВЕРСІЇ КОДУ: там дійсно
// перезавантаження, і воно справді стирає введене.
//
// ── ЦІНА, НАЗВАНА ЧЕСНО ────────────────────────────────────────────────────
//
// Будь-яка зміна в закладі перезапитує всі відкриті екрани цього закладу,
// навіть ті, що цих даних не показують. Для салону з чотирма майстрами
// це одиниці запитів на хвилину. Пачка змін (приймання на двадцять
// позицій) склеюється затримкою нижче в один запит.
export function Live({ tenantId }: { tenantId: string }) {
  const router = useRouter()
  const [, startRefresh] = useTransition()

  useEffect(() => {
    if (!tenantId) return
    const supabase = createClient()

    let timer: ReturnType<typeof setTimeout> | null = null

    const refresh = () => {
      timer = null
      // Без мережі оновлювати нема чим. Майстер біля крісла працює офлайн
      // штатно (черга дій, М12) — тихий запит у нікуди там зайвий.
      if (typeof navigator !== 'undefined' && navigator.onLine === false) return
      // У фоні не оновлюємось: людина цього не бачить, а запит із телефона
      // коштує трафіку. Повернення в застосунок закриває оболонка
      // (`components/app-shell.tsx`) — вона перезапитує вміст на кожне
      // повернення, і саме вона лишається запасним шляхом, якщо звʼязок
      // реального часу обірвався і пульсів ми не бачили зовсім.
      if (document.visibilityState !== 'visible') return
      startRefresh(() => router.refresh())
    }

    // Затримка не для економії, а тому що одна дія людини — це часто
    // десяток рядків у базі: приймання документом пише позиції, рухи
    // складу і собівартість окремими записами, і кожен підіймає пульс.
    // Без склейки екран перезапитався б десять разів підряд.
    const soon = () => {
      if (timer) clearTimeout(timer)
      timer = setTimeout(refresh, 400)
    }

    const channel = supabase
      .channel(`pulse:${tenantId}`)
      .on(
        'postgres_changes',
        {
          event: '*',
          schema: 'public',
          table: 'tenant_pulse',
          filter: `tenant_id=eq.${tenantId}`,
        },
        soon,
      )
      .subscribe()

    // Слухача повернення в застосунок тут НЕМАЄ навмисно: він уже стоїть
    // в оболонці, і другий такий самий означав би два запити на кожне
    // повернення. Один обробник — один власник поведінки.

    return () => {
      if (timer) clearTimeout(timer)
      void supabase.removeChannel(channel)
    }
  }, [tenantId, router])

  return null
}
