#!/usr/bin/env bash
# ===========================================================================
# Внешняя проверка живости. Шаг 2, пункт В
# ===========================================================================
#
# ── Почему не «страница открылась» ────────────────────────────────────────
#
# Сторож, который дёргает главную и радуется двумстам, бесполезен. Главная
# отдаётся из кеша и остаётся живой, когда база лежит, очередь стоит,
# а расписание не выполняется. Такой сторож молчит ровно в тех случаях,
# ради которых его ставили.
#
# Поэтому здесь проверяются СЦЕНАРИИ. Расчёт на то, как устроен Next:
# страница, которая рендерится на сервере и по дороге ходит в базу, при
# отказе базы отдаёт не «пустую страницу», а пятисотую. Значит проверка
# «страница отдала 200 И в ней есть строка, которой без данных не будет»
# — это и есть проверка сценария, а не наличия сервера.
#
#   /api/health   — приложение живо, доходит до Supabase, политики целы,
#                   переменные окружения на месте.
#   /             — главная собирается.
#   /search?q=…   — публичный поиск. Идёт через `search_all` на сервере:
#                   сломанная функция или политика даст 500, а не пустоту.
#   /map          — карта. Идёт через `map_tenants`, тот же расчёт.
#   /t/<slug>     — витрина живого магазина. Адрес берётся из базы, поэтому
#                   проверка не устареет при переименовании.
#   /login        — только код ответа, и почему так — сказано на месте.
#
# ── Что проверяется в базе, и почему не через веб ─────────────────────────
#
# Очередь уведомлений и расписание анониму не видны и не должны быть видны
# (правило 7 — список публичных точек закрыт). Поэтому сюда они приходят
# не через сайт, а прямой строкой подключения, которая есть только у этой
# проверки.
#
#   очередь     — сколько писем ждут отправки дольше получаса. Растущая
#                 очередь значит, что разбор не идёт, и узнать об этом надо
#                 раньше клиента, не получившего напоминание за два часа.
#   расписание  — когда pg_cron последний раз отработал. Тишина дольше
#                 двадцати минут при расписании раз в пять означает, что
#                 крон мёртв, даже если всё остальное отвечает.
#   отказы      — упавшие задания за последний час. Задание может исправно
#                 запускаться и исправно падать.
#   выключено   — задание можно ВЫКЛЮЧИТЬ, и тогда оно не падает и не
#                 запускается. Молчаливее этого не бывает.
#
# ── Требуется ─────────────────────────────────────────────────────────────
#
#   SUPABASE_DB_URL — строка подключения. ОБЯЗАТЕЛЬНО Session pooler:
#                     раннеры GitHub ходят только по IPv4, а Direct
#                     у Supabase отдаётся по IPv6 и не резолвится.
#   HEALTH_BASE_URL — необязательно, по умолчанию боевой домен.
#
# Проверки базы пропускаются, если строки подключения нет, — тогда работают
# только внешние. Это осознанно: проверка без прав должна ослабнуть,
# а не соврать зелёным.
# ===========================================================================

set -uo pipefail

BASE="${HEALTH_BASE_URL:-https://cres-ca.com}"
FAILURES=()
LINES=()

note() { LINES+=("$1"); echo "$1"; }
# Отказ печатается в stdout, а НЕ в stderr. Первая редакция писала его
# в stderr — и в сводке задания, которая собирается из stdout, остались
# одни «ok». Сводка, где не видно отказа, — это сторож, который кричит
# в пустую комнату.
fail() { FAILURES+=("$1"); LINES+=("ПОМИЛКА: $1"); echo "ПОМИЛКА: $1"; }

# ── Внешние проверки ──────────────────────────────────────────────────────

# $1 — путь, $2 — ожидаемый код, $3 — строка, которая обязана быть в теле
check_page() {
  local path="$1" want="$2" needle="$3"
  local body code started elapsed
  started=$(date +%s%3N)
  body=$(curl -sS --max-time 25 --compressed \
              -H 'Cache-Control: no-cache' \
              -H 'User-Agent: cresca-health/1' \
              -w '\n%{http_code}' "$BASE$path" 2>&1)
  code="${body##*$'\n'}"
  body="${body%$'\n'*}"
  elapsed=$(( $(date +%s%3N) - started ))

  if [ "$code" != "$want" ]; then
    fail "$path — код $code, очікували $want (${elapsed}ms)"
    return
  fi
  if [ -n "$needle" ] && ! printf '%s' "$body" | grep -qF -- "$needle"; then
    fail "$path — код $want, але вмісту «$needle» немає: сторінка віддалася порожньою"
    return
  fi
  note "ok  $path (${elapsed}ms)"
}

note "── Зовнішні перевірки: $BASE"

# /api/health отвечает 503 при своей же поломке — тогда важно и тело,
# поэтому его разбираем отдельно, а не через check_page.
HEALTH=$(curl -sS --max-time 25 -w '\n%{http_code}' "$BASE/api/health" 2>&1)
HEALTH_CODE="${HEALTH##*$'\n'}"
HEALTH_BODY="${HEALTH%$'\n'*}"
if [ "$HEALTH_CODE" = "200" ] && printf '%s' "$HEALTH_BODY" | grep -q '"status":"ok"'; then
  note "ok  /api/health"
else
  fail "/api/health — код $HEALTH_CODE, тіло: $(printf '%s' "$HEALTH_BODY" | head -c 400)"
fi

check_page "/" 200 "Для українських підприємців"

# Запрос закодирован процентами намеренно. Кириллица, отданная curl как
# есть, уходит сырыми байтами в строке запроса, и часть узлов на пути
# отвечает на это четырёхсотой. Проверено попыткой: первый прогон сторожа
# уронил ровно эту строку, при том что в браузере адрес открывался.
# Браузер кодирует сам, curl — нет.
check_page "/search?q=%D0%BA%D0%B0" 200 "Послуги"

check_page "/map" 200 ""

# Вход проверяется ТОЛЬКО кодом ответа, и это ограничение, а не небрежность.
# Страница входа целиком клиентская (`'use client'` + `useSearchParams`),
# поэтому с сервера приезжает пустая оболочка: ни «Код на пошту», ни любой
# другой надписи в ней нет — проверено выборкой тела. Двухсотый ответ здесь
# доказывает, что маршрут собрался и отдаётся; что вход РАБОТАЕТ, он
# не доказывает и делать вид, что доказывает, нельзя. Настоящая проверка
# входа — сценарий в браузере, и её место в дымовых тестах, а не тут.
check_page "/login" 200 ""

# ── Проверки базы ─────────────────────────────────────────────────────────

if [ -z "${SUPABASE_DB_URL:-}" ]; then
  note "── База пропущена: SUPABASE_DB_URL не задано"
else
  note "── Перевірки бази"

  q() { psql "$SUPABASE_DB_URL" -qtAX -v ON_ERROR_STOP=1 -c "$1" 2>&1; }

  STUCK=$(q "select count(*) from public.notification_outbox
              where status = 'pending' and created_at < now() - interval '30 minutes';")
  if ! [[ "$STUCK" =~ ^[0-9]+$ ]]; then
    fail "черга — запит не виконався: $STUCK"
  elif [ "$STUCK" -gt 0 ]; then
    fail "черга — $STUCK сповіщень чекають понад 30 хвилин: розбір не йде"
  else
    note "ok  черга порожня"
  fi

  LAST=$(q "select coalesce(extract(epoch from now() - max(end_time))::int, 999999)
              from cron.job_run_details d join cron.job j on j.jobid = d.jobid
             where j.jobname = 'notifications-dispatch' and d.status = 'succeeded';")
  if ! [[ "$LAST" =~ ^[0-9]+$ ]]; then
    fail "розклад — запит не виконався: $LAST"
  elif [ "$LAST" -gt 1200 ]; then
    fail "розклад — notifications-dispatch мовчить $((LAST / 60)) хв (розклад кожні 5)"
  else
    note "ok  розклад відпрацював $((LAST / 60)) хв тому"
  fi

  BROKEN=$(q "select count(*) from cron.job_run_details
               where start_time > now() - interval '1 hour' and status <> 'succeeded';")
  if ! [[ "$BROKEN" =~ ^[0-9]+$ ]]; then
    fail "розклад — запит про відмови не виконався: $BROKEN"
  elif [ "$BROKEN" -gt 0 ]; then
    fail "розклад — $BROKEN невдалих запусків за годину"
  else
    note "ok  відмов розкладу немає"
  fi

  OFF=$(q "select coalesce(string_agg(jobname, ', '), '') from cron.job where not active;")
  if [ -n "$OFF" ] && [ "${OFF:0:5}" != "ERROR" ]; then
    fail "розклад — вимкнені завдання: $OFF"
  fi

  # ── Витрина: адрес берётся из базы, а не зашивается ─────────────────────
  #
  # Зашитый slug — это проверка, которая молча умрёт в день, когда магазин
  # переименуют, и никто этого не заметит: она продолжит ходить по старому
  # адресу и получать 404, а её отключат как «шумную». Поэтому адрес каждый
  # раз спрашивается у базы.
  #
  # Пока опубликованных витрин нет — проверка честно пропускается. Молчание
  # тут значит «нечего проверять», а не «всё хорошо», и сказано это вслух.
  SLUG=$(q "select slug from public.tenants
             where status = 'active' and storefront_enabled
             order by created_at limit 1;")
  if [ "${SLUG:0:5}" = "ERROR" ]; then
    fail "вітрина — запит про slug не виконався: $SLUG"
  elif [ -z "$SLUG" ]; then
    note "--  вітрин ще немає: перевірку пропущено"
  else
    check_page "/t/$SLUG" 200 ""
  fi
fi

# ── Итог ──────────────────────────────────────────────────────────────────

echo
if [ ${#FAILURES[@]} -eq 0 ]; then
  echo "Все живе."
  exit 0
fi

echo "Відмов: ${#FAILURES[@]}"
# Отчёт для письма и для сводки задания — единым файлом, чтобы текст
# не собирался дважды и не разъезжался.
{
  printf '%s\n' "${LINES[@]}"
} > health-report.txt
exit 1
