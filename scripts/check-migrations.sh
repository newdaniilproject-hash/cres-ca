#!/usr/bin/env bash
# Сверка применённых миграций со списком файлов. Шаг 2, пункт Б.
#
# ── Зачем ─────────────────────────────────────────────────────────────────
#
# Миграция, применённая на боевую базу и не положенная в репозиторий, —
# это не «мелкий беспорядок». Это значит, что репозиторий БОЛЬШЕ НЕ ОПИСЫВАЕТ
# продукт: развернув его с нуля, получаешь другую базу. Тесты при этом
# зелёные — они гоняют то, что в файлах, а не то, что в проде.
#
# Так уже терялись:
#   • 0023_notifications_delivery, 0024_account_deletion и правка register_tenant
#     (найдено 11.08.2026, восстановлено из журнала применённого);
#   • 0057_fix_delete_my_account_storage и 0058_delete_my_account_full_cascade
#     (найдено 15.08.2026 ЭТОЙ ПРОВЕРКОЙ, восстановлено оттуда же).
#     Обе — про удаление аккаунта, то есть про требование Apple 5.1.1(v)
#     и про условие сделки «данные клиента — его собственность».
#
# Дважды одно и то же за четыре дня — значит нужен не призыв «класть файлы»,
# а проверка, которая роняет сборку.
#
# ── Как сверяем ───────────────────────────────────────────────────────────
#
# ПО ИМЕНАМ БЕЗ НОМЕРА, а не по номерам и не по количеству.
#
# Номера сравнивать нельзя: в базе версия — это отметка времени
# (20260815110118), в файлах — порядковый номер (0071_). Общего ключа нет.
# Количество сравнивать мало: две потерянные и две лишние дают ноль разницы.
#
# А вот содержательное имя совпадает с обеих сторон, если отбросить
# ведущий номер. Проверено на живых данных: `0069_receipt_guard_message`
# в файле и `0069_receipt_guard_message` в базе; `0070_count_lines_numeric`
# в файле и `count_lines_numeric` в базе — совпадают после нормализации.
#
# Вторая половина различий как раз показывает, что имя в базе может быть
# без номера: так получается, когда миграцию применяют инструментом,
# а файл кладут руками. Это не ошибка, пока имена сходятся.

set -euo pipefail

: "${SUPABASE_DB_URL:?нет SUPABASE_DB_URL — сверять не с чем}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MIG="$ROOT/supabase/migrations"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Нормализация: убрать путь, расширение и ведущий номер с подчёркиванием.
norm() { sed -e 's|.*/||' -e 's|\.sql$||' -e 's|^[0-9]\{1,5\}_||'; }

ls "$MIG"/*.sql | norm | sort > "$WORK/files.txt"

psql "$SUPABASE_DB_URL" -tAc \
  'select name from supabase_migrations.schema_migrations order by version' \
  | norm | sed '/^$/d' | sort > "$WORK/applied.txt.raw"

# Три миграции называются в базе иначе, чем в файле — расхождение осознанное
# и объяснено в supabase/migrations/NAME-ALIASES.txt. Приводим имя из базы
# к имени файла ДО сравнения. Послабления в самой сверке при этом нет:
# всё, чего нет в списке соответствий, по-прежнему роняет проверку.
cp "$WORK/applied.txt.raw" "$WORK/applied.txt"
ALIASES="$MIG/NAME-ALIASES.txt"
if [ -f "$ALIASES" ]; then
  while read -r in_db in_file; do
    case "$in_db" in ''|\#*) continue ;; esac
    [ -n "$in_file" ] || continue
    sed -i "s|^${in_db}$|${in_file}|" "$WORK/applied.txt"
  done < "$ALIASES"
  sort -o "$WORK/applied.txt" "$WORK/applied.txt"
fi

N_FILES=$(wc -l < "$WORK/files.txt")
N_APPLIED=$(wc -l < "$WORK/applied.txt")

echo "▸ файлів у репозиторії: $N_FILES"
echo "▸ застосовано в базі:   $N_APPLIED"

MISSING="$(comm -13 "$WORK/files.txt" "$WORK/applied.txt")"   # в базе есть, файла нет
EXTRA="$(comm -23 "$WORK/files.txt" "$WORK/applied.txt")"     # файл есть, в базе нет

FAIL=0

if [ -n "$MISSING" ]; then
  FAIL=1
  echo
  echo "!! ЗАСТОСОВАНО НА БАЗІ, АЛЕ НЕМАЄ ФАЙЛУ В РЕПОЗИТОРІЇ:" >&2
  printf '   %s\n' $MISSING >&2
  echo >&2
  echo "   Репозиторій більше не описує продукт: розгорнувши його з нуля," >&2
  echo "   отримаєш ІНШУ базу. Відновити текст можна з журналу застосованого:" >&2
  echo >&2
  echo "     select array_to_string(statements, E';\\n')" >&2
  echo "       from supabase_migrations.schema_migrations where name = '…';" >&2
fi

if [ -n "$EXTRA" ]; then
  # Не всегда отказ: на ветке файл появляется раньше, чем миграция уезжает
  # на прод. Поэтому предупреждение, а не падение, — но громкое.
  echo
  echo "⚠ Є файл, але на базі не застосовано:"
  printf '   %s\n' $EXTRA
  echo "   Якщо це нова міграція з цієї гілки — усе гаразд, застосуйте її."
  echo "   Якщо ні — хтось поклав файл і забув виконати."
fi

if [ "$FAIL" = "0" ] && [ -z "$EXTRA" ]; then
  echo
  echo "✔ репозиторій і база сходяться повністю"
fi

exit "$FAIL"
